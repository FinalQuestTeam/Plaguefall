"""Compile the six existing epilogue panels using the opening's VDP pipeline."""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import sys
import textwrap

import numpy as np
from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parent
GAME = ROOT.parents[1]
sys.path.insert(0, str(GAME / 'tools'))
from text_codec import encode
spec = importlib.util.spec_from_file_location('intro_palette', GAME / 'art/intro-monologo-v1/export_intro.py')
palette = importlib.util.module_from_spec(spec)
spec.loader.exec_module(palette)
W, H = 336, 176


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    shots = json.loads((ROOT / 'storyboard.json').read_text())['shots']
    blobs = [bytearray(), bytearray(), bytearray()]
    captions, declarations, scenes, previews = [], [], [], []
    files = {}
    for index, shot in enumerate(shots):
        source = GAME / 'art/storyboard-campanha-v1/imagens' / shot['source']
        panel = Image.open(source).convert('RGB').crop(shot['box'])
        visible = ImageOps.fit(panel, (320, H), Image.Resampling.LANCZOS, centering=tuple(shot['center']))
        framed = Image.new('RGB', (W, H))
        framed.paste(visible, (8, 0))
        framed.paste(visible.crop((0, 0, 1, H)).resize((8, H)), (0, 0))
        framed.paste(visible.crop((319, 0, 320, H)).resize((8, H)), (328, 0))
        pixels = np.asarray(framed, dtype=np.float32).copy()
        t = np.linspace(0, 1, 48)
        pixels[-48:] *= (1 - t*t*(3-2*t))[:, None, None]
        tiles, groups, colors, image = palette.convert(Image.fromarray(np.rint(pixels).astype(np.uint8)))
        for blob, data in zip(blobs, (tiles, groups, colors)):
            blob.extend(data)
        first, seconds = len(captions), 0
        for caption in shot['captions']:
            text = caption['text'].upper()
            encode(text)
            lines = textwrap.wrap(text, width=36, break_long_words=False, break_on_hyphens=False)
            letters = sum(map(len, lines))
            assert 1 <= len(lines) <= 4 and max(map(len, lines)) <= 36
            assert caption['seconds'] - letters/36 >= 1.5
            captions.append('    { %d, %d, %d, { %s } },' % (caption['seconds'], letters, len(lines),
                ', '.join(json.dumps(line, ensure_ascii=False) for line in lines+['']*(4-len(lines)))))
            seconds += caption['seconds']
        declarations.append(f'    {{ {seconds}, {first}, {len(captions)-first} }},')
        scenes.append(dict(index=index, **shot, seconds=seconds))
        dest = ROOT / f'frames/{index:02}.png'
        if args.check:
            assert Image.open(dest).convert('RGB').tobytes() == image.tobytes(), dest
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            image.save(dest)
        previews.append(image)
    for name, blob in zip(('tiles', 'groups', 'palettes'), blobs):
        files[GAME / f'res/ending/{name}.bin'] = bytes(blob)
    files[GAME / 'res/ending_data.res'] = b'''// Existing storyboard epilogue: six alternatives, three slides per run.
BIN ending_tiles "ending/tiles.bin" 4
BIN ending_groups "ending/groups.bin" 2
BIN ending_palettes "ending/palettes.bin" 2
'''
    files[GAME / 'src/system/video/screens/ending_shots.h'] = ('''// Generated by art/ending-slides-v1/export_ending.py.
#ifndef ENDING_SHOTS_H
#define ENDING_SHOTS_H
#define ENDING_TILES_W 42
#define ENDING_TILES_H 22
#define ENDING_FRAME_TILES (ENDING_TILES_W * ENDING_TILES_H)
typedef struct {
    u8 seconds, letters, lineCount;
    const char *lines[4];
} EndingCaption;
typedef struct { u8 seconds, firstCaption, captionCount; } EndingShot;
static const EndingCaption ENDING_CAPTIONS[] = {
'''+'\n'.join(captions)+'''\n};
static const EndingShot ENDING_SHOTS[] = {
'''+'\n'.join(declarations)+'\n};\n#endif\n').encode()
    for path, data in files.items():
        if args.check:
            assert path.read_bytes() == data, path
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    sequences = [[(1 if flags&1 else 0), (3 if flags&2 else 2), (5 if flags&4 else 4)] for flags in range(8)]
    report = dict(passed=True, scenes=scenes, sequences=sequences,
        durations=[sum(scenes[i]['seconds'] for i in sequence) for sequence in sequences],
        files={str(p.relative_to(GAME)):dict(bytes=len(data), sha256=hashlib.sha256(data).hexdigest()) for p,data in files.items()})
    if not args.check:
        (ROOT / 'export.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
        board = Image.new('RGB', (W*2, (H+24)*3), (16,16,20))
        draw = ImageDraw.Draw(board)
        for i, image in enumerate(previews):
            x,y = i%2*W, i//2*(H+24)
            board.paste(image, (x,y))
            draw.text((x+8,y+H+4), f'{i:02} / {shots[i]["panel"]}', fill='white')
        board.save(ROOT / 'contact-sheet.png')
    print('PASS: six epilogue panels, seven captions, eight independent endings', report['durations'])


if __name__ == '__main__':
    main()
