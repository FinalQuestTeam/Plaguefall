"""Convert imagegen animation sheets to the production 4bpp sprite palette.

Only technical extraction, uniform scaling, alpha thresholding and palette
indexing are performed here. Every visible animation frame comes from its
saved generated source; this script does not draw replacement sprite art.
"""
from pathlib import Path
import argparse
import hashlib
import io
import json
import struct
from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]
PALETTE = json.loads((GAME/'art/cangaco-insects-sized-v3/palette.json').read_text())
ASSETS = [('nest',48,48),('generator',32,32),('cargo',32,32),
          ('transmitter',32,32),('valve',32,32),('gate',64,64),
          ('trap',32,32),('radio',32,32),('refugee',32,48),('cage',64,64)]


def indexed(rgba):
    result = Image.new('P',rgba.size)
    result.putpalette(sum(PALETTE,[])+[0]*720)
    result.info['transparency']=0
    cache={}
    pixels=[]
    for r,g,b,a in rgba.get_flattened_data():
        if a<128:pixels.append(0);continue
        color=(r,g,b)
        if color not in cache:
            cache[color]=min(range(1,16),key=lambda i:sum((x-y)**2 for x,y in zip(color,PALETTE[i])))
        pixels.append(cache[color])
    result.putdata(pixels)
    return result


def extract(path,width,height):
    image=Image.open(path).convert('RGBA');cw=image.width//3;ch=image.height//2
    assert image.width%3==0 and image.height%2==0,(path,image.size)
    cells=[image.crop((i%3*cw,i//3*ch,(i%3+1)*cw,(i//3+1)*ch)) for i in range(6)]
    boxes=[cell.getchannel('A').point(lambda a:255 if a>=192 else 0).getbbox() for cell in cells]
    assert all(boxes),(path,boxes)
    # One uniform scale across the complete sequence. Gate cells are registered
    # to the fixed south jamb, so the leaf can fold without moving the mount.
    centers=json.loads((HERE/'gate-mount.json').read_text())['source_mount_center_x'] if path.stem=='gate' else [cw/2]*6
    half=max(max(cx-b[0],b[2]-cx) for b,cx in zip(boxes,centers))
    tallest=max(b[3]-b[1] for b in boxes)
    scale=min((width-2)/(half*2),(height-2)/tallest)
    frames=[]
    for cell,box,cx in zip(cells,boxes,centers):
        cropped=cell.crop(box)
        resized=cropped.resize((max(1,round(cropped.width*scale)),max(1,round(cropped.height*scale))),Image.Resampling.NEAREST)
        frame=Image.new('RGBA',(width,height))
        left=round(width/2+(box[0]-cx)*scale)
        frame.alpha_composite(resized,(left,height-1-resized.height))
        frames.append(indexed(frame))
    # Terminal mechanism states represent successful operation in gameplay.
    # Reuse the authored powered/open pose, rather than the source's damage
    # study, for frame5. No replacement pixels are drawn.
    if path.stem in ('generator','valve'):frames[5]=frames[3].copy()
    if path.stem=='cargo':frames[5]=frames[4].copy()
    return frames,boxes


def pack(frame):
    if frame.size==(32,48):
        return pack(frame.crop((0,0,32,32)))+pack(frame.crop((0,32,32,48)))
    result=bytearray();p=frame.load()
    for tx in range(frame.width//8):
        for ty in range(frame.height//8):
            for y in range(8):
                for x in range(0,8,2):result.append(p[tx*8+x,ty*8+y]*16+p[tx*8+x+1,ty*8+y])
    return bytes(result)


def png(image):
    buf=io.BytesIO();image.save(buf,format='PNG');return buf.getvalue()


def generate():
    files={};metadata=[];parts=[];offset=0;all_frames=[]
    for name,width,height in ASSETS:
        source=HERE/f'source/{name}.png';frames,boxes=extract(source,width,height)
        data=b''.join(map(pack,frames));parts.append(data)
        for i,frame in enumerate(frames):files[HERE/f'frames/{name}-{i}.png']=png(frame)
        atlas=Image.new('P',(width*6,height));atlas.putpalette(frames[0].getpalette());atlas.info['transparency']=0
        for i,frame in enumerate(frames):atlas.paste(frame,(i*width,0))
        files[HERE/f'frames/{name}-strip.png']=png(atlas)
        metadata.append(dict(name=name,width=width,height=height,frames=6,tiles_per_frame=width*height//64,
                             offset_words=offset,pose_mapping=([0,1,2,3,4,3] if name in ('generator','valve') else [0,1,2,3,4,4] if name=='cargo' else list(range(6))),source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                             source_boxes=boxes,bytes=len(data)))
        offset+=len(data)//4;all_frames.append(frames)
    data=b''.join(parts)
    files[GAME/'res/objectives/animations.bin']=data
    header=['// Generated by art/objective-sprites-v1/export.py; imagegen-authored art.',
            '#ifndef OBJECTIVE_ART_DATA_H','#define OBJECTIVE_ART_DATA_H',
            'typedef struct { u32 offset; u16 tiles; u8 width,height; } ObjectiveArt;',
            'static const ObjectiveArt objectiveArt[%d]={'%len(ASSETS)]
    for a in metadata:header.append('{%u,%u,%u,%u},'%(a['offset_words'],a['tiles_per_frame'],a['width'],a['height']))
    header+=['};','static const u8 objectiveTileVisible[]={']
    visible=[int(any(data[i:i+32])) for i in range(0,len(data),32)]
    for i in range(0,len(visible),32):header.append(','.join(map(str,visible[i:i+32]))+',')
    header+=['};','#endif','']
    files[GAME/'src/system/video/objective_art_data.h']='\n'.join(header).encode()
    files[HERE/'assets.json']=(json.dumps({'palette':'cangaco-insects-sized-v3/palette.json','assets':metadata,
        'total_bytes':len(data),'export':'imagegen sources; shared scale and ground anchor; nearest-neighbor; existing 15 opaque colors'},indent=2)+'\n').encode()
    preview=Image.new('RGB',(6*112+180,len(ASSETS)*100),(27,34,32));d=ImageDraw.Draw(preview)
    for row,((name,w,h),frames) in enumerate(zip(ASSETS,all_frames)):
        d.text((6,row*100+40),name,fill=(219,182,36))
        scale=min(96//w,88//h)
        for col,frame in enumerate(frames):
            rgb=frame.convert('RGBA').resize((w*scale,h*scale),Image.Resampling.NEAREST)
            preview.paste(rgb,(180+col*112+(96-w*scale)//2,row*100+88-h*scale),rgb)
    files[HERE/'atlas-nearest.png']=png(preview)
    for frame in range(6):
        board=Image.new('RGB',(len(ASSETS)*96,96),(27,34,32))
        for i,((name,w,h),frames) in enumerate(zip(ASSETS,all_frames)):
            factor=min(88//w,88//h);im=frames[frame].convert('RGBA').resize((w*factor,h*factor),Image.Resampling.NEAREST)
            board.paste(im,(i*96+(96-w*factor)//2,92-h*factor),im)
        if frame==0:animation=[]
        animation.append(board)
    gif=io.BytesIO();animation[0].save(gif,format='GIF',save_all=True,append_images=animation[1:],duration=[600,250,150,150,200,700],loop=0)
    files[HERE/'animation-preview.gif']=gif.getvalue()
    return files


if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for path,data in generate().items():
        if args.check:assert path.read_bytes()==data,path
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('Ten objective sprites, six authored frames each, production palette and fixed anchors.')
