"""Technical export of image_gen art: crop, nearest-neighbour and shared PAL1."""
from pathlib import Path
from PIL import Image
import argparse,hashlib,importlib.util,json,struct
ROOT=Path(__file__).resolve().parent
GAME=ROOT.parents[1]
spec=importlib.util.spec_from_file_location('pixels',GAME/'art/cangaco-insects-iso60-v2/export_sprites.py')
pixels=importlib.util.module_from_spec(spec);spec.loader.exec_module(pixels)

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    source=ROOT/'originals/santa-aparecida.png'
    image=Image.open(source).convert('RGBA')
    image.putalpha(image.getchannel('A').point(lambda a:255 if a>=128 else 0))
    source_box=image.getbbox();box=source_box;assert box
    crop=image.crop(box);ratio=min(22/crop.width,22/crop.height)
    crop=crop.resize((max(1,round(crop.width*ratio)),max(1,round(crop.height*ratio))),Image.Resampling.NEAREST)
    frame=Image.new('RGBA',(24,24));frame.paste(crop,((24-crop.width)//2,23-crop.height))
    frame=pixels.indexed(frame)
    halo=Image.new('P',(8,8));halo.putpalette(frame.getpalette())
    for y in range(8):
        for x in range(8):
            value=frame.getpixel((x+8,y))
            if value in (4,5,12):halo.putpixel((x,y),1 if value==4 else 4)
    assert halo.getbbox(),'crown glow must contain visible pixels'
    icon=frame.resize((8,8),Image.Resampling.NEAREST)
    header='// Generated by art/santa-aparecida-v1/export_sprite.py; shared PAL1.\n#ifndef SAINT_DATA_H\n#define SAINT_DATA_H\n#include <genesis.h>\n'
    sizes=[]
    for name,asset in [('SAINT24_DATA',frame),('SAINT_ICON_DATA',icon),('SAINT_HALO_DATA',halo)]:
        raw=pixels.pack(asset,[(0,0,*asset.size)]);sizes.append(len(raw))
        words=struct.unpack('>'+str(len(raw)//4)+'I',raw)
        header+='static const u32 '+name+'['+str(len(words))+'] = {\n'
        for i in range(0,len(words),8):header+='    '+','.join('0x%08xUL'%n for n in words[i:i+8])+',\n'
        header+='};\n'
    header+='#endif\n'
    assert sizes==[288,32,32]
    target=GAME/'src/system/video/sprites/saint_data.h'
    if args.check:
        assert target.read_text()==header
        for name,expected in [('santa-aparecida.png',frame),('halo.png',halo),('icone.png',icon)]:
            path=ROOT/name;saved=Image.open(path)
            assert saved.mode=='P' and saved.size==expected.size and saved.tobytes()==expected.tobytes()
            assert saved.info['transparency']==0 and path.read_bytes()[24]==4
            assert saved.getpalette()[:48]==[v for rgb in pixels.PALETTE for v in rgb]
            assert set(saved.convert('RGBA').getchannel('A').tobytes())=={0,255}
    else:
        target.write_text(header)
        for name,asset in [('santa-aparecida.png',frame),('halo.png',halo),('icone.png',icon)]:asset.save(ROOT/name,bits=4,transparency=0)
        frame.convert('RGBA').resize((240,240),Image.Resampling.NEAREST).save(ROOT/'santa-aparecida-10x.png')
        (ROOT/'paleta.json').write_text(json.dumps(pixels.PALETTE,indent=2)+'\n')
    box=frame.getbbox();assert box[0]>=1 and box[1]>=1 and box[2]<=23 and box[3]<=23
    report={'passed':True,'sprite_size':[24,24],'frame_count':1,'visible_colors':len(set(frame.tobytes())-{0}),'transparent_index':0,'binary_alpha':True,'shared_palette':'PAL1, identical to insects/objects','body_tiles':9,'hud_tiles':1,'glow_tiles':1,'total_tiles':11,'vram_delta_bytes':0,'additional_runtime_ram_bytes':0,'sprite_pieces':'1 body + existing optional8x8 glow','npc_hitbox':[24,24],'npc_logic_changed':False,'source_crop':source_box,'native_bounds':box,'technical_export':'Generated enlarged art cropped, nearest-neighbour registered to native size and palette indexed; no procedural drawing.','camera':'Visual high camera target60deg above ground; exact3D angle cannot be measured from raster.','source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'header_sha256':hashlib.sha256(header.encode()).hexdigest()}
    if not args.check:(ROOT/'validation.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
if __name__=='__main__':main()
