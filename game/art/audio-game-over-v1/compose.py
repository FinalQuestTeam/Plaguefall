"""Export the approved game-over cue, Cinza e Silencio, for game and bench."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parent


def hz(note):
    names = {"C":0,"C#":1,"D":2,"E":4,"F":5,"G":7,"A":9,"Bb":10}
    return round(440 * 2 ** (((int(note[-1])+1)*12 + names[note[:-1]]-69)/12))


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    events = []

    def note(at, pitch, length, voice, volume, style=0):
        assert at >= 0 and length > 0 and at + length <= 24
        events.append(dict(at=round(at*100), frequency=hz(pitch) if voice<3 else pitch,
            length=round(length*100), voice=voice, volume=volume, style=style))

    # The upward opening/victory motif returns as a quiet falling answer.
    for at,pitch,length in [(0,"D5",3),(3,"A4",3),(6,"F4",2),
                            (8,"E4",4),(12,"D4",2),(16,"C#4",2),(18,"D4",6)]:
        note(at,pitch,length,0,6)
    # Dm / Bb / Gm / A7 / Dm(add9), without a major victory resolution.
    for at,pitches in [(0,["F4","A4"]),(4,["D4","F4"]),
                       (8,["Bb3","D4"]),(12,["C#4","G4"])]:
        note(at,pitches[0],2,1,10)
        note(at+2,pitches[1],2,1,11,1)
    note(16,"E4",2,1,11,1)
    note(18,"A4",2,1,11,1)
    note(20,"F4",4,1,10)
    for at,pitch in [(0,"D3"),(4,"Bb2"),(8,"G3"),(12,"A2")]:
        note(at,pitch,3.4,2,9,1)
    note(16,"A2",2,2,11,1)
    note(18,"D3",6,2,9)
    # A final industrial breath; percussion drops out before the last phrase.
    for at,kind,length,volume in [(0,2,.65,11),(3,0,.4,13),
                                  (4,1,.45,13),(8,2,.5,13)]:
        note(at,kind,length,3,volume,1)
    events.sort(key=lambda event:(event['at'],event['voice']))
    for voice in range(4):
        end=0
        for event in events:
            if event['voice']==voice:
                assert event['at']>=end
                end=event['at']+event['length']
    header='// Generated by ../../compose.py. Audition only; 600 Hz clock.\nstatic const Event SCORE[] = {\n'
    for event in events:
        header+='    {%d, %d, %d, %d, %d, %d},\n'%tuple(event.values())
    header+='};\n#define EVENT_COUNT (sizeof(SCORE)/sizeof(SCORE[0]))\n#define SCORE_TICKS 2400\n'
    production=header.replace('Generated by ../../compose.py. Audition only;',
        'Generated by game/art/audio-game-over-v1/compose.py;')
    production=production.replace('Event SCORE','MusicCueEvent GAME_OVER_SCORE').replace('EVENT_COUNT','GAME_OVER_EVENT_COUNT').replace('SCORE_TICKS','GAME_OVER_TICKS').replace('sizeof(SCORE)','sizeof(GAME_OVER_SCORE)').replace('sizeof(SCORE[0])','sizeof(GAME_OVER_SCORE[0])')
    outputs={ROOT/'bench/src/score.h':header,
        ROOT.parents[1]/'src/system/audio/game_over_data.h':production,
        ROOT/'score.json':json.dumps(dict(title='Cinza e Silêncio',bpm=90,
            meter='2/4',seconds=4,harmony=['Dm','Bb','Gm','A7','Dm(add9)'],events=events),indent=2)+'\n'}
    for path,content in outputs.items():
        if args.check:
            assert path.read_text()==content, f'Stale score: {path}'
        else:path.write_text(content)
    print(f'Exported {len(events)} events; four-second approved game-over cue.')


if __name__=='__main__':main()
