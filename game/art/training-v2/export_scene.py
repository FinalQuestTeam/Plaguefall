"""Native diagnostic floor, reusing the game's existing stone char map."""
from pathlib import Path
import re, argparse
ROOT=Path(__file__).resolve().parent;GAME=ROOT.parents[1]
s=(GAME/'src/system/video/sprites/floor_data.h').read_text()
rows=re.findall(r'"([0-9a-f]{32})"',s.split('FLOOR_STONE_ART')[1].split('};')[0]);assert len(rows)==32
pixels=[[int(v,16) for v in row] for row in rows]
tiles=[]
for tx in range(4):
 for ty in range(4):tiles.append([[pixels[ty*8+y][tx*8+x] for x in range(8)] for y in range(8)])
tiles += [ [[9 if y==0 else 6 if y==7 else 1 if x==0 else 3 if x==7 else 4 for x in range(8)] for y in range(8)],
 [[14 if x in (0,7) or y in (0,7) else 6 if y<3 else 3 for x in range(8)] for y in range(8)],
 [[12 if (x*3+y*5+y//2)%8<2 else 11 if (x+y)%3 else 10 for x in range(8)] for y in range(8)],
 [[13 if (x*3+y*5)%7<4 else 5 for x in range(8)] for y in range(8)] ]
solids=[(96,96,16,112,True),(96,192,144,16,True),(224,80,16,80,True),(288,160,64,16,False),(400,160,16,64,True),(448,160,16,64,True)]
lava=(288,256,112,64);mud=(336,80,112,48)
def inside(x,y,r):a,b,w,h=r[:4];return a<=x<a+w and b<=y<b+h
def mapping(w,h,collision=False):
 out=[]
 for y in range(48):
  for x in range(64):
   xx,yy=x*8,y*8;t=(x%4)*4+y%4
   if xx<16 or xx>=w-16 or yy<72 or yy>=(h-16 if collision else h-8):t=16
   if collision:
    for r in solids:
     if inside(xx,yy,r):t=16 if r[4] else 17
   out.append(t)
 return out
words=[sum(c<<(28-x*4) for x,c in enumerate(row)) for t in tiles for row in t]
def array(kind,name,values,hexadecimal=False):
 f=(lambda v:f'0x{v:08x}UL') if hexadecimal else str
 return f'static const {kind} {name}[{len(values)}]={{\n'+''.join('    '+','.join(map(f,values[i:i+16]))+',\n' for i in range(0,len(values),16))+'};\n'
code='// Generated by art/training-v2/export_scene.py; native diagnostic geometry.\n#include "levels/test_scene.h"\n'
code+=array('u32','testTiles',words,True)
code+=array('u16','labMap',mapping(320,224))+array('u16','collisionMap',mapping(512,384,True))
code+='static const u16 testPalette[16]={0x000,0x244,0x222,0x222,0x222,0x224,0x244,0x222,0x222,0x48a,0x026,0x28e,0x24a,0x6ac,0x864,0xeee};\n'
code+='static const ArenaScene labScene={.tiles=testTiles,.map=labMap,.palette=testPalette,.tileCount=20,.rows=48};\n'
code+='static const ArenaScene collisionScene={.tiles=testTiles,.map=collisionMap,.palette=testPalette,.tileCount=20,.rows=48};\n'
code+='static const ArenaRect collisionSolids[]={'+','.join('{'+','.join(map(str,r[:4]))+','+('TRUE' if r[4] else 'FALSE')+'}' for r in solids)+'};\n'
code+='const ArenaDef TEST_LAB_arena={320,224,16,88,303,215,260,184,NULL,0,&labScene};\n'
code+='const ArenaDef TEST_ITEMS_arena={320,224,16,88,303,215,64,144,NULL,0,&labScene};\n'
code+='const ArenaDef TEST_COMBAT_arena={320,224,16,88,303,215,152,184,NULL,0,&labScene};\n'
code+='const ArenaDef TEST_COLLISION_arena={512,384,16,88,495,367,48,112,collisionSolids,6,&collisionScene};\n'
code+='const TileRect TEST_lava[1]={{36,32,14,8}};\nconst TileRect TEST_mud[1]={{42,10,14,6}};\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
target=GAME/'src/levels/test_scene.c'
if args.check:
 assert target.read_text()==code, 'Training scene export is stale'
 print('Training: native scene export verified.')
else:
 target.write_text(code)
 print('Training: native maps, six solids, lava and mud exported.')
