"""Export approved shot A and image_gen death drawings; no synthesized poses."""
from pathlib import Path
from PIL import Image
import json,struct,hashlib,argparse
ROOT=Path(__file__).resolve().parent
GAME=ROOT.parents[2]
PALETTE=json.loads((GAME/'art/cangaco-insects-sized-v3/palette.json').read_text())
GROUPS=[['sq_red','sq_yellow','sq_orange','tri_red'],['tri_yellow','tri_purple','tri_orange'],['pen_red','pen_yellow','pen_orange'],['sq_purple','pen_purple','boss']]
IDS=['sq_red','sq_yellow','sq_purple','sq_orange','tri_red','tri_yellow','tri_purple','tri_orange','pen_red','pen_yellow','pen_purple','pen_orange','dummy','target','boss']
SIZES=[16,16,32,16,16,16,16,16,24,24,32,24,24,24,48]
def indexed(im):
 out=Image.new('P',im.size);out.putpalette([v for c in PALETTE for v in c]+[0]*720)
 cache={};pixels=[]
 for p in im.convert('RGBA').get_flattened_data():
  if p[3]<220:pixels.append(0);continue
  rgb=p[:3]
  if rgb not in cache:cache[rgb]=min(range(1,16),key=lambda c:sum((rgb[k]-PALETTE[c][k])**2 for k in range(3)))
  pixels.append(cache[rgb])
 out.putdata(pixels);out.info['transparency']=0;return out
def pack(im):
 s=im.width;parts=[(0,0,s,s)] if s<=32 else [(0,0,32,32),(0,32,32,16),(32,0,16,32),(32,32,16,16)]
 b=bytearray()
 for x,y,w,h in parts:
  for tx in range(x,x+w,8):
   for ty in range(y,y+h,8):
    for py in range(8):
     for px in range(0,8,2):b.append(im.getpixel((tx+px,ty+py))*16+im.getpixel((tx+px+1,ty+py)))
 return b
def outputs():
 result={};native={};report=[]
 for group,ids in enumerate(GROUPS):
  im=Image.open(ROOT/f'source/mortes-{group}.png').convert('RGBA')
  for r,id in enumerate(ids):
   crops=[]
   for c in range(3):
    crop=im.crop((round(c*im.width/3),round(r*im.height/len(ids)),round((c+1)*im.width/3),round((r+1)*im.height/len(ids))))
    mask=crop.getchannel('A').point(lambda a:255 if a>=220 else 0)
    assert mask.getbbox(),(group,id,c)
    crop.putalpha(mask);crops.append(crop.crop(mask.getbbox()))
   size=SIZES[IDS.index(id)]
   scale=min((size-2)/max(i.width for i in crops),(size-2)/max(i.height for i in crops))
   frames=[]
   for crop in crops:
    small=crop.resize((max(1,round(crop.width*scale)),max(1,round(crop.height*scale))),Image.Resampling.NEAREST)
    cell=Image.new('RGBA',(size,size));cell.paste(small,((size-small.width)//2,size-1-small.height));frames.append(indexed(cell))
   assert len(set(f.tobytes() for f in frames))==3,(id,'indistinct poses')
   native[id]=frames
 raw=bytearray();layout=[]
 for id,size in zip(IDS,SIZES):
  if id not in native:layout.append((0,0));continue
  layout.append((len(raw)//4,size*size//64))
  frames=native[id];sheet=Image.new('P',(size*3,size));sheet.putpalette(frames[0].getpalette())
  for n,f in enumerate(frames):sheet.paste(f,(n*size,0));raw.extend(pack(f))
  result[f'native/{id}.png']=(sheet,'image')
  report.append({'id':id,'size':size,'frames':3,'rom_bytes':size*size//2*3})
 shots=Image.open(ROOT.parent/'assets/disparos-8direcoes.png').convert('RGBA');bullet=bytearray()
 for row in range(5):
  for d in [0,2,1]:bullet.extend(pack(indexed(shots.crop((8*d,8*row,8*d+8,8*row+8)))))
 assert len(bullet)==480 and len(raw)==11808
 header='// Generated by art/disparos-mortes-ux-v1/integracao/exportar.py\n#ifndef COMBAT_ART_LAYOUT_H\n#define COMBAT_ART_LAYOUT_H\n#include <genesis.h>\ntypedef struct {u32 offset;u16 tiles;} CombatDeathArt;\nstatic const CombatDeathArt COMBAT_DEATH_ART[15]={\n'+''.join('    {%d,%d},\n'%v for v in layout)+'};\n#endif\n'
 result['../../../src/system/video/combat_art_layout.h']=(header,'text')
 result['../../../res/combat/shots.bin']=(bullet,'bytes')
 result['../../../res/combat/deaths.bin']=(raw,'bytes')
 result['../../../res/combat_art.res']=('BIN combat_shots "combat/shots.bin" 4\nBIN combat_deaths "combat/deaths.bin" 4\n','text')
 result['export.json']=(json.dumps({'species':report,'shot_bytes':len(bullet),'death_bytes':len(raw),'palette':'Existing PAL1','sources':{str(f.relative_to(ROOT)):hashlib.sha256(f.read_bytes()).hexdigest() for f in sorted((ROOT/'source').glob('mortes-*.png'))}},ensure_ascii=False,indent=2)+'\n','text')
 return result
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
 for rel,(data,kind) in outputs().items():
  path=ROOT/rel
  if args.check:
   if kind=='image':assert Image.open(path).tobytes()==data.tobytes(),path
   elif kind=='text':assert path.read_text()==data,path
   else:assert path.read_bytes()==data,path
  else:
   path.parent.mkdir(parents=True,exist_ok=True)
   if kind=='image':data.save(path,transparency=0,bits=4)
   elif kind=='text':path.write_text(data)
   else:path.write_bytes(data)
 print('Verified' if args.check else 'Exported','13 species /39 death frames /480 shot bytes /11808 death bytes')
if __name__=='__main__':main()
