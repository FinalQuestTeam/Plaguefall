"""Export the reconstructed FinalQuest logo to the existing splash renderer."""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json

import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent
GAME = ROOT.parents[1]
TARGET = GAME / "src/system/video/sprites/logo_data.h"


def logo():
    source = Image.open(ROOT / "originals/finalquest.png").convert("RGB")
    pixels = np.asarray(source)
    yy, xx = np.where(pixels.max(axis=2) > 64)
    crop = source.crop((int(xx.min()), int(yy.min()), int(xx.max())+1, int(yy.max())+1))
    fitted = ImageOps.contain(crop, (184, 120), Image.Resampling.LANCZOS)
    canvas = Image.new("RGB", (192, 128))
    canvas.paste(fitted, ((192-fitted.width)//2, (128-fitted.height)//2))
    # Fixed clean VDP greys and orange: keep the bold wordmark and icon bright,
    # spending intermediate colours on their edges instead of background noise.
    colors = np.array([(0,0,0),(1,1,1),(2,2,2),(3,3,3),(4,4,4),(5,5,5),(6,6,6),(7,7,7),
                       (7,4,0),(7,3,0),(6,3,0),(5,2,0),(4,2,0),(3,1,0),(2,1,0),(1,0,0)])
    levels = np.array([round(i*255/7) for i in range(8)])
    rgb = levels[colors]
    src = np.asarray(canvas).astype(np.int32)
    indices = ((src[:,:,None,:]-rgb[None,None,:,:])**2).sum(axis=3).argmin(axis=2)
    image = Image.fromarray(indices.astype(np.uint8), mode="P")
    image.putpalette(rgb.astype(np.uint8).flatten().tolist()+[0]*(768-48))
    image.info["transparency"] = 0
    words = [int(r)<<1 | int(g)<<5 | int(b)<<9 for r,g,b in colors]
    rows = ["".join(format(int(v),"x") for v in row) for row in indices]
    header = '''// Generated by art/finalquest-logo-v2/export_logo.py from the reconstructed brand.
#ifndef LOGO_DATA_H
#define LOGO_DATA_H
#include <genesis.h>
#define LOGO_W 192
#define LOGO_H 128
#define LOGO_TILES_W 24
#define LOGO_TILES_H 16
static const u16 LOGO_PAL[16] = { ''' + ", ".join(f"0x{w:03X}" for w in words) + ''' };
static const char *const LOGO_ART[LOGO_H] =
{
''' + "".join(f'    "{row}",\n' for row in rows) + '};\n#endif // LOGO_DATA_H\n'
    info = dict(canvas=[192,128],art_size=list(fitted.size),tiles=384,tile_bytes=12288,
                source_sha256=hashlib.sha256((ROOT/'originals/finalquest.png').read_bytes()).hexdigest(),
                header_sha256=hashlib.sha256(header.encode()).hexdigest(), generation="built-in image_gen reconstruction; original identity reference")
    return header, image, info


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    header,image,info=logo()
    if args.check:
        assert TARGET.read_text()==header
        assert Image.open(ROOT/'logo-native.png').tobytes()==image.tobytes()
    else:
        TARGET.write_text(header)
        for folder in [ROOT,GAME/'art/title-caatinga-v1']:
            image.save(folder/'logo-native.png',bits=4,transparency=0)
            image.convert('RGB').resize((576,384),Image.Resampling.NEAREST).save(folder/'logo-3x.png')
        (ROOT/'export.json').write_text(json.dumps(dict(passed=True,**info),indent=2)+'\n')
    print(json.dumps(dict(passed=True,**info),indent=2))


if __name__=='__main__':main()
