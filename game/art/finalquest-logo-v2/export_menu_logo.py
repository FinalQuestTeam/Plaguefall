"""Pack the existing FinalQuest brand as a small transparent menu credit."""
from pathlib import Path
import argparse
import hashlib
import json

import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent
GAME = ROOT.parents[1]
TARGET = GAME / 'src/system/video/sprites/finalquest_menu_data.h'
SOURCE = ROOT / 'originals/finalquest-menu-faithful-v4.png'

# The previously approved, pixel-aligned seven-row FinalQuest lettering.
WORDMARK = {
    'F': ('1111','1000','1000','1110','1000','1000','1000'),
    '!': ('11','11','11','11','11','00','11'),
    'n': ('0000','0000','1110','1001','1001','1001','1001'),
    'a': ('0000','0000','0110','0001','0111','1001','0111'),
    'l': ('1','1','1','1','1','1','1'),
    'Q': ('01110','10001','10001','10001','10101','10010','01101'),
    'u': ('0000','0000','1001','1001','1001','1001','0111'),
    'e': ('0000','0000','0110','1001','1111','1000','0111'),
    's': ('0000','0000','0111','1000','0110','0001','1110'),
    't': ('010','010','111','010','010','010','001'),
}


def native_wordmark(indices):
    # Clear only the old caption; retain the tip of the inclined controller
    # where its silhouette extends into the first two caption rows.
    tail = indices[28:30,13:23].copy()
    indices[28:] = 0
    indices[28:30,13:23] = tail
    mask = np.zeros_like(indices,dtype=bool)
    accent = np.zeros_like(mask)
    name = 'F!nalQuest'
    width = sum(len(WORDMARK[c][0]) for c in name) + len(name)-1
    x = (indices.shape[1]-width)//2
    for char in name:
        for y,row in enumerate(WORDMARK[char]):
            for col,pixel in enumerate(row):
                if pixel == '1':
                    mask[31+y,x+col] = True
                    if char == '!': accent[31+y,x+col] = True
        x += len(WORDMARK[char][0])+1
    for y,x in zip(*np.where(mask)):
        indices[y-1:y+2,x-1:x+2] = 1
    indices[mask] = 15
    indices[accent] = 8


def export():
    colors = np.array([(0,0,0), (0,0,0), (1,1,1), (2,2,2), (3,3,3),
                       (4,4,4), (5,5,5), (6,6,6), (7,4,0), (7,3,0),
                       (6,3,0), (5,2,0), (4,2,0), (3,1,0), (2,1,0), (7,7,7)])
    rgb = np.rint(colors*255/7).astype('uint8')
    source = Image.open(SOURCE).convert('RGBA')
    source = source.crop(source.getchannel('A').point(lambda a: 255 if a >= 128 else 0).getbbox())
    fitted = ImageOps.contain(source, (53,36), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (56,40))
    canvas.paste(fitted, ((56-fitted.width)//2,(40-fitted.height)//2))
    rgba = np.asarray(canvas).astype(np.int32)
    pixels = rgba[:,:,:3] * rgba[:,:,3,None] // 255
    indices = ((pixels[:,:,None,:]-rgb[None,None,1:,:])**2).sum(axis=3).argmin(axis=2).astype('uint8')+1
    indices[rgba[:,:,3] < 96] = 0
    native_wordmark(indices)
    tiles = indices.reshape(5,8,7,8).transpose(0,2,1,3).reshape(35,8,8)
    unique, lookup, tilemap = [], {}, []
    for tile in tiles:
        key = tile.tobytes()
        if key not in lookup:
            lookup[key] = len(unique)
            unique.append(tile)
        tilemap.append(lookup[key])
    assert len(unique) <= 35
    words = [sum(int(pixel) << ((7-x)*4) for x,pixel in enumerate(row)) for tile in unique for row in tile]
    palette = [int(r)<<1 | int(g)<<5 | int(b)<<9 for r,g,b in colors]
    header = '''// Generated by art/finalquest-logo-v2/export_menu_logo.py.
#ifndef FINALQUEST_MENU_DATA_H
#define FINALQUEST_MENU_DATA_H
#include <genesis.h>
#define FINALQUEST_MENU_TILES_W 7
#define FINALQUEST_MENU_TILES_H 5
#define FINALQUEST_MENU_X 32
#define FINALQUEST_MENU_Y 22
'''
    header += f'#define FINALQUEST_MENU_TILES {len(unique)}\n'
    header += 'static const u16 FINALQUEST_MENU_PAL[16] = { '+', '.join(f'0x{v:03X}' for v in palette)+' };\n'
    header += 'static const u8 FINALQUEST_MENU_MAP[35] = { '+', '.join(map(str,tilemap))+' };\n'
    header += 'static const u32 FINALQUEST_MENU_PIXELS[FINALQUEST_MENU_TILES * 8] = {\n'
    for offset in range(0,len(words),8):
        header += '    '+', '.join(f'0x{w:08X}' for w in words[offset:offset+8])+',\n'
    header += '};\n#endif\n'
    image = Image.fromarray(indices)
    image.putpalette(rgb.flatten().tolist()+[0]*(768-48))
    image.info['transparency'] = 0
    report = dict(canvas=[56,40], position=[256,176], margin=[8,8], scale_from_previous=0.7,
                  art_size=list(fitted.size), rendering='faithful original controller with native 7px F!nalQuest wordmark and orange exclamation',
                  unique_tiles=len(unique),
                  tile_bytes=len(unique)*32, palette='PAL0, transparent index 0, white text index 15',
                  source=str(SOURCE.relative_to(GAME)),source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                  header_sha256=hashlib.sha256(header.encode()).hexdigest())
    return header, image, report


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    header, image, report = export()
    if args.check:
        assert TARGET.read_text() == header
        assert Image.open(ROOT/'menu-credit-native.png').tobytes() == image.tobytes()
    else:
        TARGET.write_text(header)
        image.save(ROOT/'menu-credit-native.png', bits=4, transparency=0)
        (ROOT/'menu-credit-export.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
