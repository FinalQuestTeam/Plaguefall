"""Approved UI copy -> campaign footer table; verify graph coverage and text bounds."""
from pathlib import Path
import argparse,json,re

ROOT=Path(__file__).resolve().parent
GAME=ROOT.parents[1]
EXTRA=[
 ('2A','3','A RETIRADA CHEGOU AO ABRIGO.','AGORA E HORA DE DEFENDER O LOCAL.'),
 ('2B','3','O GRUPO CONSEGUIU VENCER O DESVIO.','O ABRIGO PRECISA DE PROTECAO.'),
 ('4','5','A PASSAGEM PELOS TUNEIS FOI ABERTA.','O POVO PODE CHEGAR A PLATAFORMA.'),
 ('6A','7','O POVO CONSEGUIU EMBARCAR.','OS RASTROS LEVAM A REDE DE ANTENAS.'),
 ('6B','7','A RETIRADA POR TERRA CONTINUA.','SIGA OS RASTROS ATE AS ANTENAS.'),
 ('7','8','OS RASTROS SEGUEM PELOS CABOS.','ELES LEVAM A FORNALHA DA BASE.'),
 ('8','9','OS DUTOS APONTAM PARA A BASE.','SIGA O RASTRO ATE A ALFANDEGA.'),
 ('10A','11','O ACESSO DOS TECNICOS FOI ABERTO.','O DEPOSITO FICA LOGO ADIANTE.'),
 ('10B','11','VOCE ATRAVESSOU O DRENO TERMICO.','SIGA AO DEPOSITO DE DEMOLICAO.'),
 ('11','12','AS CARGAS DE DEMOLICAO ESTAO AQUI.','SIGA ATE A COMPORTA DE CARGA.'),
 ('13A','14','A LINHA QUENTE FICOU PARA TRAS.','OS ENXAMES GUARDAM A ENTRADA.'),
 ('13B','14','VOCE ATRAVESSOU A DECANTACAO.','OS ENXAMES GUARDAM A ENTRADA.'),
 ('14','15','O PATIO DOS ENXAMES FOI VENCIDO.','AS GALERIAS LEVAM AO NINHO CENTRAL.'),
 ('15','16','O ULTIMO BLOQUEIO FICOU PARA TRAS.','O ESCORPIAO ESPERA NA CAMARA CENTRAL.'),
]

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
 approved=json.loads((ROOT/'proposta.json').read_text())['cases']
 rows=[(c['current'],c['next'],c['cause'],c['consequence']) for c in approved]+EXTRA
 assert len(set((a,b) for a,b,_,_ in rows))==len(rows)
 graph=re.sub(r'//[^\n]*','',(GAME/'src/levels/graph.c').read_text()).split('const LevelNode GRAPH')[1]
 nodes=list(re.finditer(r'\[N_(\w+)\]\s*=\s*FASE(?:_FINAL)?\("([^"]+)"',graph))
 edges=set()
 for i,m in enumerate(nodes):
  body=graph[m.end():nodes[i+1].start() if i+1<len(nodes) else graph.index('};',m.end())]
  edges.update((m.group(2),n) for n in re.findall(r'N_(\w+)',body))
 assert edges=={(a,b) for a,b,_,_ in rows},(edges,rows)
 for _,_,cause,result in rows:
  for line in (cause,result):
   assert len(line)<=38 and all(32<=ord(c)<128 for c in line),line
 table='// Generated by art/routemap-footer-ux-v1/export_footer.py.\n#ifndef ROUTEMAP_COPY_H\n#define ROUTEMAP_COPY_H\ntypedef struct { u8 from, to; const char *cause, *result; } RouteCopy;\nstatic const RouteCopy ROUTE_COPY[] = {\n'
 for a,b,cause,result in rows:
  table+=f'    {{ N_{a}, N_{b}, {json.dumps(cause)}, {json.dumps(result)} }},\n'
 table+='};\n#endif\n'
 target=GAME/'src/system/video/screens/routemap_copy.h'
 manifest={'approvedExamples':len(approved),'coveredEdges':len(rows),'maxCharacters':max(len(s) for _,_,c,r in rows for s in (c,r)),
           'cases':[dict(current=a,next=b,cause=c,consequence=r) for a,b,c,r in rows]}
 dest=ROOT/'integracao/copy.json'
 if args.check:
  assert target.read_text()==table
  assert json.loads(dest.read_text())==manifest
 else:
  target.write_text(table);dest.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
 print(f'Footer: {len(rows)} graph edges; {len(approved)} approved examples; all lines <=38 columns.')

if __name__=='__main__':main()
