def words(raw):return list(struct.unpack('>'+str(len(raw)//2)+'H',raw))
def unpack(raw):return [v for b in raw for v in (b>>4,b&15)]
def pack(p):return bytes((p[i]<<4)|p[i+1] for i in range(0,len(p),2))
def palette(path):return words(path.read_bytes())
def rgb(p):return [(((c>>1)&7)*255//7,((c>>5)&7)*255//7,((c>>9)&7)*255//7) for c in p]
def load(folder,width):
 raw=(folder/'tiles.bin').read_bytes();ts=[raw[i:i+32] for i in range(0,len(raw),32)];m=words((folder/'map.bin').read_bytes());cols=width//8
 return [[ts[m[y*cols+x]] for x in range(cols)] for y in range(len(m)//cols)]
def remap(source,sourcepal,targetpal):
 a,b=rgb(sourcepal),rgb(targetpal)
 lut=[min(range(16),key=lambda i:sum((a[j][k]-b[i][k])**2 for k in range(3))) for j in range(16)]
 return [[pack([lut[v] for v in unpack(t)]) for t in row] for row in source]
def canvas(width,height,source,rect):
 sx,sy,sw,sh=[v//8 for v in rect]
 return [[source[sy+y%sh][sx+x%sw] for x in range(width//8)] for y in range(height//8)]
def stamp(out,source,rect,dest,repeat=None):
 sx,sy,sw,sh=[v//8 for v in rect];dx,dy=[v//8 for v in dest];dw,dh=[v//8 for v in (repeat or rect[2:])]
 for y in range(dh):
  for x in range(dw):out[dy+y][dx+x]=source[sy+y%sh][sx+x%sw]
def stamp_rubble(out,palette_words,position):
 colors=rgb(palette_words)
 image=Image.open(ART/'source/rubble.png').convert('RGBA')
 image=image.crop(image.getchannel('A').getbbox())
 patch=ImageOps.contain(image,(56,32),Image.Resampling.LANCZOS)
 sprite=Image.new('RGBA',(56,32));sprite.paste(patch,((56-patch.width)//2,32-patch.height))
 for ty in range(4):
  for tx in range(7):
   address_x=position[0]//8+tx;address_y=position[1]//8+ty
   pixels=unpack(out[address_y][address_x])
   for y in range(8):
    for x in range(8):
     r,g,b,a=sprite.getpixel((tx*8+x,ty*8+y))
     if a>=128:pixels[y*8+x]=min(range(16),key=lambda n:sum((colors[n][k]-[r,g,b][k])**2 for k in range(3)))
   out[address_y][address_x]=pack(pixels)
 sprite.save(ART/'source/rubble-native.png')

def c_array(name,ctype,data,per=12):
 width=8 if ctype=='u32' else 4
 return 'static const '+ctype+' '+name+'[] = {\n'+''.join('    '+', '.join('0x'+format(v,'0'+str(width)+'X') for v in data[i:i+per])+',\n' for i in range(0,len(data),per))+'};\n'
def export(name,m,pal,extras=()):
 tiles=[];index={}
 def intern(t):
  if t not in index:index[t]=len(tiles);tiles.append(t)
  return index[t]
 tilemap=[intern(t) for row in m for t in row];extra=[intern(t) for t in extras]
 assert len(tiles)<=640,(name,len(tiles),'VRAM budget')
 raw=b''.join(tiles);mapraw=struct.pack('>'+str(len(tilemap))+'H',*tilemap)
 folder=ART/name;folder.mkdir(exist_ok=True)
 (folder/'tiles.bin').write_bytes(raw);(folder/'map.bin').write_bytes(mapraw);(folder/'palette.bin').write_bytes(struct.pack('>16H',*pal))
 include=c_array(name+'_tiles','u32',list(struct.unpack('>'+str(len(raw)//4)+'I',raw)),8)+c_array(name+'_map','u16',tilemap)+c_array(name+'_palette','u16',pal)
 (SRC/('campaign_early_'+name+'.inc')).write_text('// Generated by art/campaign-early-v1/build.py.\n'+include)
 image=Image.new('RGB',(len(m[0])*8,len(m)*8));colors=rgb(pal)
 for y,row in enumerate(m):
  for x,t in enumerate(row):
   patch=Image.new('RGB',(8,8));patch.putdata([colors[v] for v in unpack(t)]);image.paste(patch,(x*8,y*8))
 image.save(folder/'map-native.png');image.resize((image.width*2,image.height*2),Image.Resampling.NEAREST).save(folder/'map-2x.png')
 atlas=Image.new('RGB',(128,((len(tiles)+15)//16)*8))
 for n,t in enumerate(tiles):
  patch=Image.new('RGB',(8,8));patch.putdata([colors[v] for v in unpack(t)]);atlas.paste(patch,(n%16*8,n//16*8))
 atlas.save(folder/'tileset.png')
 return {'tiles':len(tiles),'map_sha256':hashlib.sha256(mapraw).hexdigest(),'atlas_sha256':hashlib.sha256(raw).hexdigest(),'width':image.width,'height':image.height,'palette_colors':16,'lossy_tile_replacements':0,'native_modules_only':name!='church_ruins'},extra

def traversable(d,x,y,size=16):
 l,t,r,b=d['bounds']
 return l<=x<=r-size+1 and t<=y<=b-size+1 and not any(x<a+w and x+size>a and y<c+h and y+size>c for a,c,w,h,*_ in d['solids'])
def geometry(d):
 start=tuple(d['start']);assert traversable(d,*start)
 todo=deque([start]);visited={start};cols=0
 while todo:
  x,y=todo.popleft()
  for p in ((x+8,y),(x-8,y),(x,y+8),(x,y-8)):
   if p not in visited and traversable(d,*p):visited.add(p);todo.append(p)
 l,t,r,b=d['bounds'];free={(x,y) for y in range(t,b-14,8) for x in range(l,r-14,8) if traversable(d,x,y)}
 # Starts are aligned to the walkable tile grid, enabling complete reachability.
 assert visited==free,(len(visited),len(free),'unreachable free cells')
 if 'exit' in d:
  a,c,w,h=d['exit'];assert any(a<=x+8<a+w and c<=y+8<c+h for x,y in visited),'exit unreachable'
 return {'footprint':16,'reachable_positions':len(visited),'free_positions':len(free),'all_free_positions_connected':True,'bounds_checks':len(free)*4}

