"""Original two-second PSG victory cue: Mais um Amanhecer.

Two bars of 2/4, quarter = 120 BPM. One unit is a sixteenth (125 ms).
The isolated bench uses the production audio arbiter, without changing the game.
"""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parent


def hz(note):
    names = {"C": 0, "C#": 1, "D": 2, "E": 4, "F": 5,
             "F#": 6, "G": 7, "A": 9, "B": 11}
    return round(440 * 2 ** (((int(note[-1]) + 1) * 12 + names[note[:-1]] - 69) / 12))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    events = []

    def note(at, pitch, length, voice, volume, style=0):
        assert at >= 0 and length > 0 and at + length <= 16
        events.append(dict(at=round(at * 75), frequency=hz(pitch) if voice < 3 else pitch,
                           length=round(length * 75), voice=voice, volume=volume, style=style))

    # Opening motif, moved upward; the answer lands on the high tonic.
    for at, pitch, length in [(0,"D5",2),(2,"F5",2),(4,"A5",2),(6,"D6",2),
                               (8,"C6",2),(10,"A5",2),(12,"D6",4)]:
        note(at, pitch, length, 0, 5)

    # Dm / G / A7 / D: the final F# supplies the hopeful major resolution.
    for at, pitches in [(0,["F4","A4","F5"]),(4,["B4","D5","G4"]),
                       (8,["C#5","E5","G4"]),(12,["F#4","A4","F#4"])]:
        for offset, pitch, length in [(1,pitches[0],1),(2,pitches[1],1),(3,pitches[2],1)]:
            note(at + offset, pitch, length, 1, 9, 1)

    # Tonic / anticipated fifth, recalling the existing baiao bass.
    for at, root, fifth in [(0,"D3","A3"),(4,"G3","D4"),(8,"A2","E3")]:
        note(at, root, 1.5, 2, 7, 1)
        note(at + 3, fifth, 0.8, 2, 9, 1)
    note(12, "D3", 4, 2, 8)

    # Low white-noise baques and a short periodic metallic answer.
    for at, kind, length, volume in [(0,2,.55,10),(1,0,.35,12),(3,1,.5,12),
                                    (4,2,.55,10),(5,0,.35,12),(7,1,.5,12),
                                    (8,2,.55,10),(10,1,.4,11),(11,1,.4,12)]:
        note(at, kind, length, 3, volume, 1)

    events.sort(key=lambda event: (event["at"], event["voice"]))
    for voice in range(4):
        end = 0
        for event in events:
            if event["voice"] == voice:
                assert event["at"] >= end
                end = event["at"] + event["length"]
    header = "// Generated by ../../compose.py. Timebase: 600 Hz.\n"
    header += "static const Event SCORE[] = {\n"
    for event in events:
        header += "    {%d, %d, %d, %d, %d, %d},\n" % tuple(event.values())
    header += "};\n#define EVENT_COUNT (sizeof(SCORE) / sizeof(SCORE[0]))\n#define SCORE_TICKS 1200\n"
    production = header.replace('Generated by ../../compose.py', 'Generated by game/art/audio-vitoria-v1/compose.py')
    production = production.replace('Event SCORE', 'MusicCueEvent VICTORY_SCORE').replace('EVENT_COUNT', 'VICTORY_EVENT_COUNT').replace('SCORE_TICKS', 'VICTORY_TICKS').replace('sizeof(SCORE)', 'sizeof(VICTORY_SCORE)').replace('sizeof(SCORE[0])', 'sizeof(VICTORY_SCORE[0])')
    outputs = {ROOT / "bench/src/score.h": header,
        ROOT.parents[1] / "src/system/audio/victory_data.h": production,
        ROOT / "score.json": json.dumps(dict(title="Mais um Amanhecer", bpm=120,
            seconds=2, meter="2/4", harmony=["Dm","G","A7","D"], events=events), indent=2) + "\n"}
    for path, content in outputs.items():
        if args.check:
            assert path.read_text() == content, f'Stale score: {path}'
        else:
            path.write_text(content)
    print(f"Exported {len(events)} events; two seconds; four PSG voices.")


if __name__ == "__main__":
    main()
