"""Export the approved, code-native 320x24 panel using the existing PAL1."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[3]
pixels = [[11] * 320 for _ in range(24)]

def rect(x, y, w, h, color):
    for yy in range(y, y + h):
        pixels[yy][x:x + w] = [color] * w

rect(0, 0, 320, 24, 10)
rect(1, 1, 318, 21, 9)
rect(2, 2, 316, 19, 11)
rect(2, 1, 316, 1, 4)
rect(2, 22, 316, 1, 9)
rect(0, 23, 320, 1, 11)
for x in (103, 237):
    rect(x, 3, 1, 18, 9)
    rect(x + 1, 3, 1, 18, 10)
words = []
for row in range(3):
    for col in range(40):
        for y in range(8):
            words.append(sum(pixels[row * 8 + y][col * 8 + x] << (28 - x * 4) for x in range(8)))
source = '// Generated by art/hud-resistencia-v1/integracao/exportar.py\n'
source += '#ifndef HUD_PANEL_DATA_H\n#define HUD_PANEL_DATA_H\n'
source += 'static const u32 HUD_PANEL_DATA[960]={\n'
source += ''.join('    ' + ','.join(f'0x{v:08x}UL' for v in words[i:i + 8]) + ',\n' for i in range(0, len(words), 8))
source += '};\n'
source += 'static const u32 HUD_FONT_MASK[256]={\n'
source += ''.join('    '+','.join(f'0x{sum(15 << (28-x*4) for x in range(8) if mask & (128>>x)):08x}UL' for mask in range(i,i+8))+',\n' for i in range(0,256,8))
source += '};\n#endif\n'
target = ROOT / 'src/system/video/screens/hud_panel_data.h'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert target.read_text() == source, 'Stale HUD panel export'
else:
    target.write_text(source)
print('HUD panel: 120 native tiles, existing object palette, opaque pixels.')
