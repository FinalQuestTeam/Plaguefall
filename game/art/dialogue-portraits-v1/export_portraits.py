"""Technical export of image_gen portraits; no procedural character drawing."""
from pathlib import Path
import argparse
import hashlib
import json
import re

from PIL import Image

ROOT = Path(__file__).resolve().parent
GAME = ROOT.parents[1]
TARGET = GAME / "src/system/video/sprites/portraits_data.h"
LEVELS = [round(i * 255 / 7) for i in range(8)]


def source_path(name):
    return ROOT / "originals" / ("comando-v2.png" if name == "comando" else f"{name}.png")


def snap(rgb):
    return tuple(LEVELS[round(c * 7 / 255)] for c in rgb)


def export(name):
    source = Image.open(source_path(name)).convert("RGBA")
    # The generated sources are square, registered busts. Preserve
    # that framing; only nearest-neighbour sampling and hardware quantization.
    assert source.width == source.height
    if name == "comando":
        # Without the hat, trim empty headroom and the outer shoulders so the
        # face remains legible at 48x48. This is a square crop, not a redraw.
        inset = round(source.width * 0.08)
        source = source.crop((inset, inset * 2, source.width - inset, source.height))
    native = source.resize((48, 48), Image.Resampling.NEAREST)
    pixels = [native.getpixel((x, y)) for y in range(48) for x in range(48)]
    samples = [rgb[:3] for rgb in pixels if rgb[3] >= 128]
    strip = Image.new("RGB", (len(samples), 1))
    strip.putdata(samples)
    quantized = strip.quantize(colors=14, method=Image.Quantize.MEDIANCUT)
    colors = quantized.getpalette()
    palette = list(dict.fromkeys(snap(colors[i:i + 3]) for i in range(0, 42, 3)))
    # Retain the tiny cyan implant/radio accents in a skin/metal-heavy palette.
    if any(b > r * 1.3 and g > r * 1.3 and b > 100 for r, g, b in samples):
        cyan = (0, 182, 219)
        if cyan not in palette:
            palette.append(cyan)
    # The priest's small white collar, grey beard and brass cross distinguish
    # him from Rex; retain these source colours instead of merging into skin.
    if name == "comando":
        for accent in [(219, 219, 219), (146, 146, 146), (219, 146, 36)]:
            if accent not in palette and len(palette) < 15:
                palette.append(accent)
    assert len(palette) <= 15
    indices = []
    for r, g, b, a in pixels:
        if a < 128:
            indices.append(0)
        else:
            index = min(range(len(palette)), key=lambda i: sum(
                (channel - target) ** 2 for channel, target in zip((r, g, b), palette[i])))
            indices.append(index + 1)
    image = Image.new("P", (48, 48))
    full_palette = [(0, 0, 0)] + palette
    full_palette += [(0, 0, 0)] * (16 - len(full_palette))
    image.putpalette([c for rgb in full_palette for c in rgb] + [0] * (768 - 48))
    image.putdata(indices)
    image.info["transparency"] = 0
    rows = ["".join(format(i, "x") for i in indices[y * 48:(y + 1) * 48]) for y in range(48)]
    words = [sum(round(rgb[c] * 7 / 255) << (1 + 4 * c) for c in range(3))
             for rgb in full_palette]
    return image, rows, words, full_palette


def legacy():
    source = (ROOT / "legacy/portraits_data.h").read_text()
    names = re.findall(r'"([A-Z]+)"', source.split("// paleta")[0])
    pals = re.findall(r"\{ ([^{}]+) \},", source.split("// char-maps")[0])
    pals = [[int(word, 16) for word in re.findall(r"0x[0-9A-Fa-f]+", row)] for row in pals]
    rows = re.findall(r'"([0-9a-f]{48})"', source)
    assert len(names) == len(pals) == 3 and len(rows) == 144
    return [(names[i], rows[i * 48:(i + 1) * 48], pals[i]) for i in range(3)]


def header(entries):
    text = """// Generated by art/dialogue-portraits-v1/export_portraits.py.
// 48x48 indexed portraits, independent 16-color Mega Drive palettes.
// Original LACRAIA preserved; original header in art package/legacy/.
// ID order must match levels/story.h. Included only by screens/story.c.
#ifndef PORTRAITS_DATA_H
#define PORTRAITS_DATA_H
#include <genesis.h>

#define PORTRAIT_COUNT 4

static const char *const PORTRAIT_NAME[PORTRAIT_COUNT] =
{
"""
    text += "    " + ", ".join(f'"{name}"' for name, _, _ in entries) + "\n};\n\n"
    text += "static const u16 PORTRAIT_PAL[PORTRAIT_COUNT][16] =\n{\n"
    for name, _, words in entries:
        text += "    { " + ", ".join(f"0x{w:03X}" for w in words) + f" }}, // {name}\n"
    text += "};\n\nstatic const char *const PORTRAIT_ART[PORTRAIT_COUNT][48] =\n{\n"
    for name, rows, _ in entries:
        text += f"    {{ // {name}\n"
        text += "".join(f'        "{row}",\n' for row in rows)
        text += "    },\n"
    return text + "};\n\n#endif // PORTRAITS_DATA_H\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    entries = legacy()
    outputs = {}
    report = {"passed": True, "generation": "built-in image_gen", "size": [48, 48],
              "portraits": {}, "resident_vram_delta_bytes": 0,
              "simultaneous_portrait_tiles": 72, "runtime_ram_delta_bytes": 0}
    for name, index in [("rex", 0), ("comando", 1), ("parceira", 3)]:
        image, rows, words, palette = export(name)
        display_name = "DINORAH" if name == "parceira" else name.upper()
        entry = (display_name, rows, words)
        if index == 3:
            entries.append(entry)
        else:
            entries[index] = entry
        assert all(len(row) == 48 for row in rows)
        assert all(0 <= w <= 0xEEE and w & 0x111 == 0 for w in words)
        assert set(image.convert("RGBA").getchannel("A").tobytes()) == {0, 255}
        assert all(c in LEVELS for rgb in palette for c in rgb)
        path = ROOT / f"{name}.png"
        if args.check:
            saved = Image.open(path)
            assert saved.size == image.size and saved.mode == "P"
            assert saved.tobytes() == image.tobytes()
            assert saved.getpalette()[:48] == image.getpalette()[:48]
            assert saved.info["transparency"] == 0 and path.read_bytes()[24] == 4
        else:
            image.save(path, bits=4, transparency=0)
            image.convert("RGBA").resize((384, 384), Image.Resampling.NEAREST).save(ROOT / f"{name}-8x.png")
            (ROOT / f"{name}-palette.json").write_text(json.dumps(palette, indent=2) + "\n")
        outputs[name] = image
        report["portraits"][name] = {
            "id": index, "display_name": display_name,
            "opaque_colors": len(set(image.tobytes()) - {0}),
            "binary_alpha": True, "transparent_index": 0,
            "source_sha256": hashlib.sha256(source_path(name).read_bytes()).hexdigest(),
            "native_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "tile_bytes_when_loaded": 1152, "palette_bytes": 32,
            "framing": "square crop: 8% each side, 16% top" if name == "comando" else "full source",
        }
    generated = header(entries)
    if args.check:
        assert TARGET.read_text() == generated
    else:
        TARGET.write_text(generated)
        # Preview is only a nearest-neighbour contact sheet of exported assets.
        preview = Image.new("RGBA", (1312, 448), (16, 16, 24, 255))
        for i, name in enumerate(("rex", "comando", "parceira")):
            large = outputs[name].convert("RGBA").resize((384, 384), Image.Resampling.NEAREST)
            preview.alpha_composite(large, (32 + 432 * i, 32))
        preview.convert("RGB").save(ROOT / "preview-8x.png")
        report["header_sha256"] = hashlib.sha256(generated.encode()).hexdigest()
        (ROOT / "validation.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
