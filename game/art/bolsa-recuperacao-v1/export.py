"""Native 16x16 adaptation of the approved leather bornal; shared object PAL1."""
import argparse
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
GAME = ROOT.parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = json.loads((ROOT / 'bag-pixels.json').read_text())
    rows, legend = source['rows'], source['palette_indices']
    assert len(rows) == 16 and all(len(row) == 16 for row in rows)
    assert set(''.join(rows)) == {'.', *legend}
    palette = json.loads((GAME / 'art/cangaco-itens-v2/palette.json').read_text())
    pixels = [legend.get(c, 0) for row in rows for c in row]
    # A continuous pale silhouette keeps brown leather visible over the floor.
    for y in range(16):
        for x in range(16):
            if not pixels[y*16+x]:
                continue
            perimeter = any(not (0 <= x+dx < 16 and 0 <= y+dy < 16) or
                            not pixels[(y+dy)*16+x+dx]
                            for dx,dy in ((-1,0),(1,0),(0,-1),(0,1)))
            if perimeter:
                assert pixels[y*16+x] == 1, (x, y, 'outer edge must be cream')
    header = '// Generated by art/bolsa-recuperacao-v1/export.py\n'
    header += '#ifndef BAG_DATA_H\n#define BAG_DATA_H\n'
    header += 'static const char *const ITEM_BAG_ART[16] = {\n'
    header += ''.join(f'    "{row}",\n' for row in rows) + '};\n'
    header += 'static const TilePixel ITEM_BAG_LEG[] = {\n'
    header += ''.join(f"    {{'{c}', {index}}},\n" for c,index in legend.items()) + '};\n#endif\n'
    target = GAME / 'src/system/video/sprites/bag_data.h'
    if args.check:
        assert target.read_text() == header, target
    else:
        target.write_text(header)
    image = Image.new('P', (16, 16))
    image.putpalette([v for color in palette for v in color] + [0] * (768-48))
    image.putdata(pixels)
    image.info['transparency'] = 0
    if args.check:
        native = Image.open(ROOT / 'bag-native.png')
        assert native.size == (16, 16) and list(native.getdata()) == pixels
        assert native.info['transparency'] == 0
    else:
        image.save(ROOT / 'bag-native.png', bits=4, transparency=0)
        image.convert('RGBA').resize((256, 256), Image.Resampling.NEAREST).save(ROOT / 'bag-native-16x.png')
    print('Bornal: 16x16, 4 tiles / 128 bytes, 4 PAL1 colors, cream outline, alpha index 0.')


if __name__ == '__main__':
    main()
