code='// Generated phase8 priority targets, from reviewed layout.\n#ifndef PHASE08_LAYOUT_H\n#define PHASE08_LAYOUT_H\nstatic const s16 PHASE08_TARGETS[3][2]={'+','.join('{'+str(x)+','+str(y)+'}' for x,y in targets)+'};\n#endif\n';emit(G/'src/levels/phase08_layout.h',code.encode())
