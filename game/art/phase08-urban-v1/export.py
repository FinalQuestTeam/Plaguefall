# Eight 8x16 strips per32x32 pose. Exact repeated strips share VRAM; blank
# strips emit no sprite. All six original poses survive without runtime tile DMA.
meta=json.loads((G/'art/objective-sprites-v1/assets.json').read_text())['assets'][3]
