bank=[];indices=[];lookup={}
for f in range(6):
 for x in range(4):
  for y in range(0,4,2):
   chunk=raw[(f*16+x*4+y)*32:(f*16+x*4+y+2)*32]
   if chunk not in lookup:lookup[chunk]=len(bank);bank.append(chunk)
   indices.append(lookup[chunk])
assert b''.join(bank[i] for i in indices)==raw
assert len(bank)*2==76 and 560+len(bank)*2<=640
blank=lookup.get(bytes(64),65535)
words=struct.unpack('>'+str(len(bank)*16)+'I',b''.join(bank))
code='// Generated phase8 exact 8x16 transmitter strips; all six poses.\nstatic const u32 phase08TransmitterTiles[]={\n'+''.join(','.join('0x%08XUL'%v for v in words[i:i+8])+',\n' for i in range(0,len(words),8))+'};\n'
code+='static const u8 phase08TransmitterStrips[]={'+','.join(map(str,indices))+'};\n#define PHASE08_TRANSMITTER_TILES 76\n#define PHASE08_TRANSMITTER_BLANK '+str(blank)+'\n'
emit(G/'src/system/video/phase08_transmitter.h',code.encode())
code='// Generated by art/phase08-urban-v1/export.py; shared phase7 art and solids.\nstatic const ArenaScene phase08Scene={.tiles=phase07_tiles,.map=phase07_map,.palette=phase07_palette,.tileCount=560,.rows=68,.cols=96,.cameraPlayerY=184,.stream=&phase07Stream,.streamOverlay=TRUE,.cameraSouthStart=352};\nconst ArenaDef CAMPAIGN_RESISTANCE_FAVELA_TARGETS={768,544,32,176,735,479,64,192,phase07Solids,4,&phase08Scene};\n'
