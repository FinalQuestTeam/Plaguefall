import argparse,json,struct,sys,io
from PIL import Image
G=Path(__file__).resolve().parents[2];A=Path(__file__).resolve().parent;S=G/'art/phase07-urban-v2'
sys.path.insert(0,str(G/'tools'))
from campaign_geometry import validate,free,path
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
def emit(p,data):
 if args.check:assert p.exists() and p.read_bytes()==data,('stale phase8 export',p)
 else:
  p.parent.mkdir(parents=True,exist_ok=True)
  if not p.exists() or p.read_bytes()!=data:p.write_bytes(data)
def js(p,data):emit(p,(json.dumps(data,ensure_ascii=False,indent=2)+'\n').encode())
def png(p,im):
 b=io.BytesIO();im.save(b,format='PNG');emit(p,b.getvalue())
m=json.loads((S/'manifest.json').read_text());targets=[[232,216],[440,432],[664,280]]
