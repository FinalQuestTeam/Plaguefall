"""Export packed image_gen menu art and the reconstructed FinalQuest logo."""
from pathlib import Path
import argparse
import hashlib
import json
import re

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
GAME = ROOT.parents[1]
SPRITES = GAME / "src/system/video/sprites"
LEVELS = np.array([round(i * 255 / 7) for i in range(8)], dtype=np.int32)


def words(colors):
    return [sum(round(int(c) * 7 / 255) << (1 + 4 * i) for i, c in enumerate(rgb))
            for rgb in colors]


def palette(pixels):
    strip = Image.fromarray(pixels.reshape(1, -1, 3).astype(np.uint8))
    quant = strip.quantize(colors=15, method=Image.Quantize.MEDIANCUT)
    values = np.array(quant.getpalette()[:45]).reshape(15, 3)
    snapped = LEVELS[np.rint(values * 7 / 255).astype(int)]
    result = [(0, 0, 0)]
    for rgb in snapped:
        value = tuple(int(c) for c in rgb)
        if value not in result:
            result.append(value)
    # Snapping can merge several quantized colours. Use the free entries for
    # hardware colours with the largest weighted residual instead of wasting
    # those entries on duplicate black (important for faces and metal glints).
    candidates, counts = np.unique(
        LEVELS[np.rint(pixels.reshape(-1, 3) * 7 / 255).astype(int)],
        axis=0, return_counts=True)
    while len(result) < 16:
        errors = ((candidates[:, None, :] - np.array(result)[None, :, :]) ** 2).sum(axis=2).min(axis=1)
        best = int((errors * counts).argmax())
        if errors[best] == 0:
            break
        result.append(tuple(int(c) for c in candidates[best]))
    result += [(0, 0, 0)] * (16 - len(result))
    return np.array(result, dtype=np.int32)


def title():
    source = Image.open(ROOT / "originals/title-caatinga.png").convert("RGB")
    small = source.resize((320, 224), Image.Resampling.LANCZOS)
    pixels = np.asarray(small).astype(np.int32)
    tiles = pixels.reshape(28, 8, 40, 8, 3).transpose(0, 2, 1, 3, 4).reshape(1120, 64, 3)
    light = tiles.mean(axis=(1, 2))
    groups = (light > np.median(light)).astype(int)
    # Each hardware tile may use only one palette. Iterate whole-tile choices
    # and palette quantization; no new objects or painted details are created.
    for _ in range(8):
        palettes = [palette(tiles[groups == i]) for i in range(2)]
        distances = [((tiles[:, :, None, :] - pal[None, None, :, :]) ** 2).sum(axis=3)
                     for pal in palettes]
        costs = np.stack([d.min(axis=2).mean(axis=1) for d in distances], axis=1)
        chosen = costs.argmin(axis=1)
        if np.array_equal(chosen, groups):
            break
        assert chosen.min() == 0 and chosen.max() == 1
        groups = chosen
    indices = np.stack([d.argmin(axis=2) for d in distances])[chosen, np.arange(1120)]
    rgb = np.stack(palettes)[chosen[:, None], indices]
    native = rgb.reshape(28, 40, 8, 8, 3).transpose(0, 2, 1, 3, 4).reshape(224, 320, 3)
    index_map = indices.reshape(28, 40, 8, 8).transpose(0, 2, 1, 3).reshape(224, 320)
    rows = ["".join(format(int(i), "x") for i in row) for row in index_map]
    tile_rows = ["".join("ab"[int(i)] for i in row) for row in chosen.reshape(28, 40)]
    header = """// Generated by art/title-caatinga-v1/export_title.py from image_gen art.
#ifndef TITLEBG_DATA_H
#define TITLEBG_DATA_H
#include <genesis.h>
#define TITLEBG_ART_W 320
#define TITLEBG_ART_H 224
#define TITLEBG_TILES_W 40
#define TITLEBG_TILES_H 28
"""
    for name, pal in zip(("A", "B"), palettes):
        header += f"static const u16 TITLEBG_PAL_{name}[16] = {{ "
        header += ", ".join(f"0x{value:03X}" for value in words(pal)) + " };\n"
    for name, dimension, data in [("TITLEBG_TILE_PAL", "TITLEBG_TILES_H", tile_rows)]:
        header += f"static const char *const {name}[{dimension}] =\n{{\n"
        header += "".join(f'    "{row}",\n' for row in data) + "};\n"
    packed_words = []
    for tile in indices:
        for py in range(8):
            word = 0
            for value in tile[py*8:py*8+8]:
                word = (word << 4) | int(value)
            packed_words.append(word)
    header += "static const u32 TITLEBG_PIXELS[TITLEBG_TILES_W * TITLEBG_TILES_H * 8] = {\n"
    for offset in range(0, len(packed_words), 8):
        header += "    " + ", ".join(f"0x{word:08X}" for word in packed_words[offset:offset+8]) + ",\n"
    header += "};\n#endif // TITLEBG_DATA_H\n"
    assert len(rows) == 224 and all(len(row) == 320 for row in rows)
    assert len(tile_rows) == 28 and all(len(row) == 40 for row in tile_rows)
    assert all(value & 0x111 == 0 for pal in palettes for value in words(pal))
    image = Image.fromarray(native.astype(np.uint8))
    return header, image, {"size": [320, 224], "tiles": 1120, "tile_bytes": 35840,
                           "palettes": [pal.tolist() for pal in palettes],
                           "tiles_per_palette": [int((chosen == i).sum()) for i in range(2)],
                           "opaque_rgb_colors": len(image.getcolors(256) or []),
                           "mean_square_error": float(costs[np.arange(1120), chosen].mean()),
                           "vram_delta_bytes": 0}


def logo():
    # The original reduction is archived; boot now uses the reconstructed mark.
    import importlib.util
    spec = importlib.util.spec_from_file_location("finalquest_logo", ROOT.parent / "finalquest-logo-v2/export_logo.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.logo()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    report = {"passed": True, "generation": "built-in image_gen for title and reconstructed FinalQuest logo; title tiles packed offline",
              "source_sha256": hashlib.sha256((ROOT / "originals/title-caatinga.png").read_bytes()).hexdigest()}
    for name, fn, target in [("title", title, "titlebg_data.h"), ("logo", logo, "logo_data.h")]:
        header, image, info = fn()
        if args.check:
            assert (SPRITES / target).read_text() == header
            saved = Image.open(ROOT / f"{name}-native.png")
            assert saved.size == image.size and saved.tobytes() == image.tobytes()
            if name == "logo":
                assert saved.info["transparency"] == 0
        else:
            (SPRITES / target).write_text(header)
            if name == "logo":
                image.save(ROOT / f"{name}-native.png", bits=4, transparency=0)
            else:
                image.save(ROOT / f"{name}-native.png")
            image.convert("RGBA").resize((image.width * 3, image.height * 3), Image.Resampling.NEAREST).save(ROOT / f"{name}-3x.png")
        info["header_sha256"] = hashlib.sha256(header.encode()).hexdigest()
        report[name] = info
    if not args.check:
        (ROOT / "validation.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
