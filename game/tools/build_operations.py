"""Eight diagnostic layouts using the existing industrial training atlas.

Mission props have their own artwork. Wall geometry and collisions share
these rectangles; evacuation jambs stay solid after the gate leaf falls.
"""
from pathlib import Path
import argparse
import re

GAME = Path(__file__).resolve().parents[1]
EVAC_GATES = [(160,168,16,48),(288,256,16,48),(416,144,16,48)]
EVAC_ROUTE = [(96,304),(112,304),(112,192),(216,192),(240,192),(240,280),(344,280),(368,280),(368,168),(456,168),(448,304)]
CONTAINMENT = (248,160,64,64)
SOLIDS = [
    [(224,128,16,80),(224,272,16,64)],
    [(224,176,64,16),(144,256,48,16)],
    [(176,176,48,16),(304,240,48,16)],
    [(176,192,48,16),(336,224,48,16)],
    [(144,200,48,16),(352,200,48,16)],
    [r for x,y,w,h in EVAC_GATES for r in ((x,96,w,y-96),(x,y+h,w,352-y-h))],
    [(176,160,16,64),(368,160,16,64),(248,160,64,8),(248,216,64,8),(304,168,8,48)],
    [(208,144,16,48),(304,144,16,48)],
]


def generate():
    old = (GAME/'src/levels/test_scene.c').read_text()
    tiles = re.search(r'static const u32 testTiles\[160\]=\{(.*?)\};', old, re.S)[1]
    palette = re.search(r'static const u16 testPalette\[16\]=\{(.*?)\};', old, re.S)[1]
    out = ['// Generated by tools/build_operations.py; reuses the approved training atlas.',
           '#include "levels/operations.h"',
           'static const u32 tiles[160]={'+tiles+'};',
           'static const u16 palette[16]={'+palette+'};']
    out += ['const ArenaRect OPS_evacGates[3]={'+','.join('{%d,%d,%d,%d,TRUE}'%r for r in EVAC_GATES)+'};']
    out += ['static const RoutePoint evacPoints[]={'+','.join('{%d,%d,0}'%p for p in EVAC_ROUTE)+'};',
            'const RouteDef OPS_evacRoute={evacPoints,sizeof(evacPoints)/sizeof(evacPoints[0]),{432,288,32,40,FALSE}};']
    for n, solids in enumerate(SOLIDS):
        grid = []
        for y in range(48):
            for x in range(64):
                tile = (x%4)*4+y%4
                if x<4 or x>=60 or y<12 or y>=44: tile=16
                if x in (4,59) or y in (12,43): tile=8+(y%4)
                if any(rx<=x*8<rx+w and ry<=y*8<ry+h for rx,ry,w,h in solids): tile=16
                grid.append(tile)
        out += [f'static const u16 map{n}[3072]={{',
                *[','.join(map(str,grid[i:i+64]))+',' for i in range(0,len(grid),64)], '};',
                f'static const ArenaRect solids{n}[]={{'+','.join('{%d,%d,%d,%d,TRUE}'%r for r in solids)+'};',
                f'static const ArenaScene scene{n}={{.tiles=tiles,.map=map{n},.palette=palette,.tileCount=20,.rows=48}};']
    out += ['const ArenaDef OPS_arenas[OPS_COUNT]={']
    for n, solids in enumerate(SOLIDS):
        start_x,start_y=(120,240) if n==7 else (56,304)
        out += [f'{{512,384,40,104,471,343,{start_x},{start_y},solids{n},{len(solids)},&scene{n}}},']
    out += ['};','']
    return '\n'.join(out)


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    target=GAME/'src/levels/operations_scenes.c';text=generate()
    if a.check: assert target.read_text()==text, 'Regenerate operations scenes'
    else: target.write_text(text)
    print('Eight operations: shared industrial tiles, matching solid geometry.')
