"""Pack the existing floor char-maps once, preserving native pixel/tile order."""
from pathlib import Path
import argparse
import re

GAME = Path(__file__).resolve().parents[1]
SOURCE = GAME / 'src/system/video/sprites/floor_data.h'
OUTPUT = GAME / 'src/system/video/sprites/floor_tiles_data.h'
NAMES = ('STONE', 'FOREST', 'CAVE', 'MIXGRASS', 'MIXROCK')


def render():
    source = SOURCE.read_text()
    words = []
    for name in NAMES:
        block = re.search(r'FLOOR_' + name + r'_ART\[32\]\s*=\s*\{(.*?)\};', source, re.S)
        assert block, name
        rows = re.findall(r'"([0-9a-f]{32})"', block.group(1))
        assert len(rows) == 32, name
        tiles = [0] * 128
        for y, row in enumerate(rows):
            for x, pixel in enumerate(row):
                tiles[((x // 8) * 4 + y // 8) * 8 + y % 8] |= int(pixel, 16) << ((7 - x % 8) * 4)
        words.extend(tiles)
    body = '\n'.join('    ' + ','.join(f'0x{v:08X}UL' for v in words[i:i+8]) + ',' for i in range(0, len(words), 8))
    return '// Generated by tools/build_floor_tiles.py; identical to floor_data.h.\n#ifndef FLOOR_TILES_DATA_H\n#define FLOOR_TILES_DATA_H\nstatic const u32 FLOOR_PACKED[640] = {\n' + body + '\n};\n#endif\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render()
    if args.check:
        assert OUTPUT.read_text() == result, 'floor export is stale'
    else:
        OUTPUT.write_text(result)
    print('Floor: five pixel-identical variants, 80 native tiles, no runtime allocation.')


if __name__ == '__main__':
    main()
