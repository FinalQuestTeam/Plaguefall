"""Export both 96-tile font variants and the shared 1bpp compositor mask."""
import argparse
import json
from pathlib import Path
from PIL import Image
from text_codec import ACCENTS, ENCODE

GAME = Path(__file__).resolve().parents[1]


def font_rows():
    font = Image.open(GAME.parent / 'SGDK/res/image/font_default.png').convert('L')
    rows = [sum(128 >> x for x in range(8) if font.getpixel((g % 16 * 8 + x, g // 16 * 8 + y)))
            for g in range(96) for y in range(8)]
    glyphs = json.loads((GAME / 'res/text/glyphs.json').read_text())
    assert set(glyphs) == set(ACCENTS)
    for ch, bitmap in glyphs.items():
        assert len(bitmap) == 8 and all(len(row) == 8 and set(row) <= {'.', '#'} for row in bitmap)
        offset = (ord(ENCODE[ch]) - 32) * 8
        rows[offset:offset + 8] = [sum(128 >> x for x, px in enumerate(row) if px == '#') for row in bitmap]
    return rows


def tile_data(rows, opaque=False):
    return bytes(sum((15 if row & (128 >> x) else int(opaque)) << (4 if x % 2 == 0 else 0)
                     for x in (pair, pair + 1)) for row in rows for pair in range(0, 8, 2))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = font_rows()
    data = '#ifndef RESULT_FONT_H\n#define RESULT_FONT_H\n// Generated by tools/build_text_font.py; 96 glyphs, Portuguese in a..l.\nstatic const u8 RESULT_FONT[768] = {\n'
    data += ''.join('    ' + ','.join(map(str, rows[i:i + 16])) + ',\n' for i in range(0, len(rows), 16)) + '};\n#endif\n'
    outputs = {GAME / 'src/system/video/screens/result_font.h': data.encode(),
               GAME / 'res/text/font.bin': tile_data(rows), GAME / 'res/intro/font.bin': tile_data(rows, True)}
    for path, content in outputs.items():
        if args.check:
            assert path.read_bytes() == content, f'Stale font: {path}'
        else:
            path.write_bytes(content)
    print('Portuguese font: 96 tiles / 3072 bytes per variant; 12 accented glyphs; no extra VRAM.')


if __name__ == '__main__':
    main()
