"""Losslessly deduplicate campaign valve/gate frames, preserving all six poses.
Sprite missions retain their contiguous atlas; campaign ground maps use indices.
"""
from pathlib import Path
import argparse,re,struct
G=Path(__file__).resolve().parents[1]
def generate():
    raw=(G/'res/objectives/animations.bin').read_bytes()
    header=(G/'src/system/video/objective_art_data.h').read_text()
    entries=[tuple(map(int,m)) for m in re.findall(r'\{(\d+),(\d+),(\d+),(\d+)\}',header)]
    out=['// Generated by tools/pack_campaign_ground_art.py; exact tile deduplication.']
    counts=[]
    for art,name in ((0,'Nest'),(1,'Generator'),(2,'Cargo'),(4,'Valve'),(5,'Gate'),(7,'Radio')):
        offset,tiles,w,h=entries[art];source=raw[offset*4:offset*4+tiles*6*32]
        bank=[];lookup={};indices=[]
        for n in range(tiles*6):
            tile=source[n*32:(n+1)*32]
            if tile not in lookup:lookup[tile]=len(bank);bank.append(tile)
            indices.append(lookup[tile])
        assert b''.join(bank[i] for i in indices)==source
        counts.append(len(bank));out+=['static const u32 campaign'+name+'Tiles[]={']
        words=struct.unpack('>'+str(len(bank)*8)+'I',b''.join(bank))
        out+= [','.join('0x%08XUL'%v for v in words[i:i+8])+',' for i in range(0,len(words),8)]
        out+=['};','static const u16 campaign'+name+'Map[]={']
        out+= [','.join(map(str,indices[i:i+16]))+',' for i in range(0,len(indices),16)]
        out+=['};']
    out+=['typedef struct { const u32 *tiles; const u16 *map; u16 count; } CampaignGroundArt;', 'static const CampaignGroundArt campaignGroundArt[10]={']
    for art,name in enumerate(('Nest','Generator','Cargo',None,'Valve','Gate',None,'Radio',None,None)):
        out.append('{campaign%sTiles,campaign%sMap,sizeof(campaign%sTiles)/32},'%(name,name,name) if name else '{NULL,NULL,0},')
    out+=['};']
    return '\n'.join(out)+'\n',counts
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    source,counts=generate();dest=G/'src/system/video/campaign_ground_art.h'
    if a.check:assert dest.read_text()==source
    else:dest.write_text(source)
    print('Campaign ground art exact reconstruction, six poses: %s tiles, %s scenery tiles available.'%(counts,640-counts[3]-counts[4]))
