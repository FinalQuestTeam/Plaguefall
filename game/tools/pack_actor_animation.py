"""Select existing native pixels for the reduced runtime animation; retain masters."""
from pathlib import Path
from PIL import Image
import json, importlib.util, hashlib, argparse, subprocess, sys
GAME=Path(__file__).resolve().parents[1]
ART=GAME/"art/cangaco-insects-iso60-v2"
spec=importlib.util.spec_from_file_location("pixel_packing",ART/"export_sprites.py")
pixels=importlib.util.module_from_spec(spec);spec.loader.exec_module(pixels)

def main():
    parser=argparse.ArgumentParser();parser.add_argument("--check",action="store_true");args=parser.parse_args()
    layout=json.loads((GAME/"res/actor_animation.json").read_text())
    idle,run=layout["idle_source_poses"],layout["run_source_poses"];poses=idle+run
    assert len(idle)==2 and len(run)==4 and all(0<=p<4 for p in idle) and all(4<=p<10 for p in run)
    assert len(set(poses))==6
    assert layout["canonical_directions"]==["N","NE","L","SE","S"]
    assert layout["horizontal_mirrors"]=={"SO":"SE","O":"L","NO":"NE"}
    assert all(n>0 and d>0 for n,d in [layout["idle_step_fps_ratio"],layout["run_step_fps_ratio"]])
    def write(path,data):
        if args.check:assert path.read_bytes()==data,path
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    header="// Generated by tools/pack_actor_animation.py from res/actor_animation.json.\n#ifndef ACTOR_ANIMATION_H\n#define ACTOR_ANIMATION_H\n"
    for name,value in [("IDLE_FRAMES",len(idle)),("RUN_FRAMES",len(run)),("VIEW_FRAMES",len(poses))]:header+=f"#define ACTOR_{name} {value}\n"
    for name in ["idle","run"]:
        num,den=layout[name+"_step_fps_ratio"]
        header+=f"#define ACTOR_{name.upper()}_TICKS(fps) divu((u32)(fps)*{num},{den})\n"
    header+="#endif\n";write(GAME/"src/system/video/actor_animation.h",header.encode())
    muzzle=json.loads((GAME/"res/heroi/muzzle.json").read_text())
    header='// Generated by tools/pack_actor_animation.py from res/heroi/muzzle.json.\n'
    header+='static const u8 HERO_MUZZLE[5][ACTOR_VIEW_FRAMES][2] = {\n'
    for direction in layout['canonical_directions']:
        anchors=[muzzle[direction][str(p)] for p in poses]
        assert all(0<=x<=32 and 0<=y<=48 for x,y in anchors)
        header+='    {'+','.join('{%d,%d}'%tuple(a) for a in anchors)+'}, // '+direction+'\n'
    header+='};\n';write(GAME/'src/system/video/hero_muzzle.h',header.encode())
    catalog=json.loads((ART/"catalog.json").read_text())
    report={"layout":layout,"actors":{}}
    for group,masters in [("insects",[(e["id"],ART/"enemies"/e["id"]/(e["id"]+".png")) for e in catalog]),("heroi",[("heroi",GAME/"art/cangaco-protagonista-iso60-v2/heroi/heroi.png")])]:
        if group=="insects" and layout.get("enemy_art_directory"):
            exporter=GAME/layout["enemy_art_directory"]/"export_sprites.py"
            subprocess.run([sys.executable,str(exporter)]+(["--check"] if args.check else []),check=True)
            data=(GAME/"res/insects/frames.bin").read_bytes()
            report["actors"][group]={"characters":13,"canonical_frames":390,"rom_bytes":len(data),"previous_rom_bytes":499200,"sha256":hashlib.sha256(data).hexdigest()}
            continue
        raw=bytearray()
        for name,path in masters:
            sheet=Image.open(path);assert sheet.mode=="P" and sheet.size==(192,768)
            for direction in range(5):
                for pose in poses:
                    row,col=(0,pose) if pose<4 else (1,pose-4)
                    cell=sheet.crop((col*32,direction*96+row*48,col*32+32,direction*96+row*48+48))
                    raw.extend(pixels.frame_bytes(cell))
        write(GAME/"res"/group/"frames.bin",raw)
        report["actors"][group]={"characters":len(masters),"canonical_frames":len(masters)*5*len(poses),"rom_bytes":len(raw),"previous_rom_bytes":len(masters)*5*10*768,"sha256":hashlib.sha256(raw).hexdigest()}
    # Keep the purple shield bank synchronized with the selected enemy art.
    subprocess.run([sys.executable,str(GAME/'tools/build_enemy_shields.py'),str(GAME)]+
                   (["--check"] if args.check else []),check=True)
    # Dinorah is currently displayed only at rest in Assets. Keep movement
    # poses in the art master, and publish just the ten displayed ROM frames.
    dinorah=(GAME/'art/cangaco-parceira-iso60-v1/runtime/frames.bin').read_bytes()
    gallery=b''.join(dinorah[(d*len(poses)+p)*768:(d*len(poses)+p+1)*768]
                     for d in range(5) for p in range(len(idle)))
    assert len(gallery)==5*len(idle)*768
    write(GAME/'res/dinorah/idle.bin',gallery)
    report['actors']['dinorah_gallery']={'canonical_frames':5*len(idle),'rom_bytes':len(gallery),
        'previous_rom_bytes':len(dinorah),'sha256':hashlib.sha256(gallery).hexdigest()}
    encoded=(json.dumps(report,indent=2)+"\n").encode()
    write((GAME/layout["enemy_art_directory"] if layout.get("enemy_art_directory") else ART)/"validation/reduced-animation.json",encoded)
    print(encoded.decode())
if __name__=="__main__":main()
