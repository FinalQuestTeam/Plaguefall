"""Code-native 16px navigation badges and 8px HUD arrows, existing PAL1 only."""
from pathlib import Path
import io,struct,argparse
from PIL import Image,ImageDraw
G=Path(__file__).resolve().parents[1]
def pack_sprite(im):
 p=im.load();out=bytearray()
 for tx in range(im.width//8):
  for ty in range(im.height//8):
   for y in range(8):
    for x in range(0,8,2):out.append(p[tx*8+x,ty*8+y]*16+p[tx*8+x+1,ty*8+y])
 return bytes(out)
def glyph(kind,color,size=16):
 im=Image.new('P',(size,size),0);d=ImageDraw.Draw(im)
 if size==16:
  d.polygon([(3,0),(12,0),(15,3),(15,12),(12,15),(3,15),(0,12),(0,3)],fill=10)
  d.polygon([(3,1),(12,1),(14,3),(14,12),(12,14),(3,14),(1,12),(1,3)],fill=9)
  d.polygon([(3,2),(12,2),(13,3),(13,12),(12,13),(3,13),(2,12),(2,3)],fill=11)
  d.line([(3,1),(12,1),(14,3)],fill=4)
  if kind=='E':
   d.rectangle((4,7,9,9),fill=9);d.polygon([(9,4),(13,8),(9,12)],fill=9)
   d.rectangle((3,6,8,8),fill=color);d.polygon([(8,3),(12,7),(8,11)],fill=color)
  elif kind=='S':
   d.rectangle((7,4,9,9),fill=9);d.polygon([(4,9),(8,13),(12,9)],fill=9)
   d.rectangle((6,3,8,8),fill=color);d.polygon([(3,8),(7,12),(11,8)],fill=color)
  else:
   d.rectangle((8,5,9,10),fill=9);d.rectangle((8,12,9,13),fill=9)
   d.rectangle((6,3,8,8),fill=color);d.rectangle((6,10,8,12),fill=color)
 else:
  if kind=='E':
   d.rectangle((0,3,4,5),fill=9);d.polygon([(4,1),(7,4),(4,7)],fill=9)
   d.rectangle((0,2,4,4),fill=color);d.polygon([(4,0),(7,3),(4,6)],fill=color)
  else:
   d.rectangle((3,0,5,4),fill=9);d.polygon([(1,4),(4,7),(7,4)],fill=9)
   d.rectangle((2,0,4,4),fill=color);d.polygon([(0,4),(3,7),(6,4)],fill=color)
 return im

def generate():
 frames=[glyph(kind,color) for kind in ('E','S','!') for color in (1,4)]
 binary=b''.join(pack_sprite(im) for im in frames)
 icons=[glyph('E',4,8),glyph('S',4,8),glyph('E',4,8).transpose(Image.Transpose.FLIP_LEFT_RIGHT),glyph('S',4,8).transpose(Image.Transpose.FLIP_TOP_BOTTOM)]
 src=['// Generated by tools/build_game_markers.py; shared interface palette.','#ifndef GAME_MARKER_ART_H','#define GAME_MARKER_ART_H','#define GAME_MARKER_TILES 24','static const u32 GAME_MARKER_ICONS[4][8]={']
 for im in icons:
  data=pack_sprite(im);src.append('{'+','.join('0x%08xUL'%v for v in struct.unpack('>8I',data))+'},')
 src+=['};','#endif','']
 pal=struct.unpack('>16H',(G/'res/insects/palette.bin').read_bytes());rgb=[tuple(((c>>s)&7)*255//7 for s in (1,5,9)) for c in pal]
 atlas=Image.new('RGB',(6*20+4,24),(23,30,25))
 for n,im in enumerate(frames):
  out=Image.new('RGB',(16,16));out.putdata([rgb[i] if i else (23,30,25) for i in im.getdata()]);atlas.paste(out,(4+n*20,4))
 b=io.BytesIO();atlas.resize((atlas.width*6,atlas.height*6),Image.Resampling.NEAREST).save(b,format='PNG')
 return {G/'res/routes/markers.bin':binary,G/'src/system/video/marker_art.h':'\n'.join(src).encode(),G/'art/objetivos-travessia-escolta-v1/integracao-2048/marcadores.png':b.getvalue()}
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
 for p,data in generate().items():
  if a.check:assert p.read_bytes()==data,p
  else:p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
 print('Markers: 24 sprite tiles + four HUD icons; shared PAL1.')
