"""Phase16 reuses the literal phase15 room; only the two engine windows change."""
from pathlib import Path
import argparse, hashlib, io, json, math, struct
import numpy as np
from PIL import Image
from build_phase14_shipyard import PALETTE, SIZE, BOUNDS, START, MACHINES
from build_phase15_shipyard import SOLIDS, ANTENNA_POSITION
from campaign_geometry import validate

G = Path(__file__).resolve().parents[1]
A = G / 'art/phase16-shipyard-v2'
S = G / 'art/phase15-shipyard-v2'
WINDOWS = [(56,16,200,96), (320,16,464,96)]


def export(check=False):
    def emit(p, data):
        if check:
            assert p.exists() and p.read_bytes() == data, ('stale phase16 export', p)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_bytes() != data:
                p.write_bytes(data)

    def png(p, im):
        b = io.BytesIO(); im.save(b, format='PNG'); emit(p, b.getvalue())

    def ca(name, kind, values):
        fmt = '0x%08XUL' if kind == 'u32' else '%d'
        return ('static const ' + kind + ' ' + name + '[] __attribute__((aligned(32)))={\n' +
                ''.join(','.join(fmt % v for v in values[i:i+8]) + ',\n'
                        for i in range(0, len(values), 8)) + '};\n')

    # One sample per native pixel, then the exact existing sixteen-color bank.
    # The generated full frame is a reference; only its inset enters the room.
    source = A / 'source/engine-window.png'
    rgb = np.array(Image.open(source).convert('RGB').resize((184,112), Image.Resampling.NEAREST), dtype=np.int32)
    colors = np.array(PALETTE, dtype=np.int32)
    window = Image.fromarray(((rgb[:,:,None,:]-colors[None,None,:,:])**2).sum(3).argmin(2).astype('uint8'))
    window.putpalette(sum(map(list, PALETTE), []) + [0]*720)
    interior = window.crop((24,16,168,96))
    png(A / 'objects/engine-window-native.png', window)
    png(A / 'objects/engine-interior-native.png', interior)
    base = Image.open(S / 'normal-native.png'); room = base.copy()
    changed = np.zeros((SIZE[1], SIZE[0]), dtype=bool)
    for x1,y1,x2,y2 in WINDOWS:
        room.paste(interior, (x1,y1)); changed[y1:y2,x1:x2] = True
    assert np.array_equal(np.array(base)[~changed], np.array(room)[~changed]), 'changed pixels outside windows'
    assert np.any(np.array(base)[changed] != np.array(room)[changed]), 'windows did not change'
    png(A / 'native.png', room)
    complete = room.convert('RGBA')
    for x,y in MACHINES:
        complete.alpha_composite(Image.open(G / 'art/phase14-shipyard-v2/objects/generator-3.png').convert('RGBA'), (x-24,y-40))
    complete.alpha_composite(Image.open(S / 'objects/radio-2.png').convert('RGBA'), ANTENNA_POSITION)
    png(A / 'complete.png', complete)

    tiles, lookup, mapping = [], {}, []
    for y in range(0, SIZE[1], 8):
        for x in range(0, SIZE[0], 8):
            tile = room.crop((x,y,x+8,y+8)).tobytes()
            if tile not in lookup:
                lookup[tile] = len(tiles); tiles.append(tile)
            mapping.append(lookup[tile])
    grid = np.array(mapping).reshape(72,64); peak = 0
    for y in range(3,48):
        for x in range(25):
            peak = max(peak, len(np.unique(grid[y:y+26,x:x+41])))
    prior = json.loads((S / 'manifest.json').read_text())
    reserve = prior['generator']['tiles'] + prior['radio_art']['tiles']
    cache = min(640-reserve, math.ceil((peak+8)/16)*16)
    assert peak <= cache and cache+reserve <= 640, ('phase16 cache overflow', peak, cache, reserve)
    raw = b''.join(bytes((t[i]<<4)|t[i+1] for i in range(0,64,2)) for t in tiles)
    restored = b''.join(b''.join(tiles[mapping[(y//8)*64+x//8]][(y%8)*8:(y%8+1)*8]
                                for x in range(0,512,8)) for y in range(576))
    assert restored == room.tobytes(), 'phase16 packing changed pixels'
    words = [(round(r*7/255)<<1)|(round(g*7/255)<<5)|(round(b*7/255)<<9) for r,g,b in PALETTE]
    for name,data in [('tiles',raw), ('map',struct.pack('>4608H',*mapping)), ('palette',struct.pack('>16H',*words))]:
        emit(A / f'native/{name}.bin', data)
    code = '// Generated by tools/build_phase16_shipyard.py; only engine windows differ from15.\n'
    code += ca('phase16Tiles','u32',struct.unpack('>'+str(len(raw)//4)+'I',raw))
    code += ca('phase16Palette','u16',words) + ca('phase16Map','u16',mapping)
    code += f'static const ArenaStream phase16Stream={{{len(tiles)}}};\n'
    code += f'static const ArenaScene phase16Scene={{.tiles=phase16Tiles,.map=phase16Map,.palette=phase16Palette,.tileCount={cache},.rows=72,.cols=64,.stream=&phase16Stream,.streamOverlay=TRUE}};\n'
    # Share the literal collision table, not a separately maintained copy.
    code += 'const ArenaDef CAMPAIGN_LAUNCH_BOSS={' + ','.join(map(str,[*SIZE,*BOUNDS,*START])) + ',phase15Solids,' + str(len(SOLIDS)) + ',&phase16Scene};\n'
    emit(G / 'src/levels/campaign_launch_phase16.inc', code.encode())
    d = dict(size=list(SIZE), bounds=BOUNDS, start=START, solids=SOLIDS, points=[], machines=MACHINES,
             radio=prior['radio'], radio_art=prior['radio_art'], antenna_position=prior['antenna_position'], generators_powered_on_entry=True, geometry=validate(dict(bounds=BOUNDS,start=START,solids=SOLIDS,points=[])),
             window=dict(size=[144,80], positions=WINDOWS, native_pixel_block=1, palette_colors=16, tile_size=[8,8]),
             unchanged_outside_windows=True, shared_equipment='phase15 native generator and radio overlays',
             memory=dict(source_tiles=len(tiles), cache_tiles=cache, maximum_visible_patterns=peak,
                         generator_tiles=prior['generator']['tiles'], radio_tiles=prior['radio_art']['tiles'],
                         total_resident_tiles=cache+reserve, heap_bytes=(len(tiles)+cache*4)*2,
                         lossy_tile_replacements=0, pixel_exact_reconstruction=True),
             sources=[dict(path=str(p.relative_to(G)),sha256=hashlib.sha256(p.read_bytes()).hexdigest())
                      for p in [source,S/'normal-native.png',S/'manifest.json']])
    emit(A / 'manifest.json', (json.dumps(d,ensure_ascii=False,indent=2)+'\n').encode())
    return d


if __name__ == '__main__':
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); args=ap.parse_args()
    print(json.dumps(export(args.check)['memory'],indent=2))
