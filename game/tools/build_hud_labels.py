"""Precompose the existing escort labels with the existing HUD/font pixels."""
from pathlib import Path
import argparse,re
G=Path(__file__).resolve().parents[1]
def words(path,name):
    body=re.search(r'\b'+name+r'\[\d+\]\s*=\s*\{(.*?)\};',path.read_text(),re.S)[1]
    return [int(x,0) for x in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b',body)]
panel=words(G/'src/system/video/screens/hud_panel_data.h','HUD_PANEL_DATA')
font=words(G/'src/system/video/screens/result_font.h','RESULT_FONT')
tables=[]
for label in ('DINORAH','COBERTURA','PASSAGEM'):
    values=[]
    for col in range(9):
        for yy in range(8):
            y=yy+3;word=panel[((y>>3)*40+col+1)*8+(y&7)]
            bits=font[(ord(label[col])-32)*8+yy] if col<len(label) else 0
            for x in range(8):
                if bits&(128>>x):word=(word&~(15<<(28-x*4)))|(1<<(28-x*4))
            values.append(word)
    tables.append(values)
source='// Generated by tools/build_hud_labels.py; identical panel/font composition.\n'
source+='#ifndef HUD_LABEL_DATA_H\n#define HUD_LABEL_DATA_H\nstatic const u32 HUD_ESCORT_LABELS[3][72]={\n'
for values in tables:
    source+=' {\n'+''.join('  '+','.join('0x%08xUL'%v for v in values[i:i+8])+',\n' for i in range(0,72,8))+' },\n'
source+='};\nstatic const u32 HUD_NATIVE_DIGITS[3][10][8]={\n'
for color in (1,2,4):
    source+=' {\n'
    for digit in range(10):
        rows=[]
        for y in range(8):
            bits=font[(ord('0')+digit-32)*8+y]
            rows.append(sum((color if bits&(128>>x) else 11)<<(28-4*x) for x in range(8)))
        source+='  {'+','.join('0x%08xUL'%v for v in rows)+'},\n'
    source+=' },\n'
source+='};\nstatic const char HUD_OBJECTIVE_NUMBERS[101][4]={\n'+''.join(' \"%03d\",\n'%i for i in range(101))+'};\n#endif\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
p=G/'src/system/video/screens/hud_label_data.h'
if args.check:assert p.read_text()==source,'Stale HUD label export'
else:p.write_text(source)
print('HUD escort labels: existing pixels, 2228 ROM bytes, no extra tiles or palettes.')
