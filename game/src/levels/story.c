const StoryEntry *STORY_find(u8 node,u8 when)
{
    if(node==N_16 && when==DEPOIS)return &endings[campaignFlags&7];
    if(campaignFlags&CAMPAIGN_DINORAH_DEAD)
        for(u8 i=0;i<sizeof(deadLate)/sizeof(deadLate[0]);i++)
            if(deadLate[i].node==node && deadLate[i].when==when)return &deadLate[i];
    for(u16 i=0;i<STORY_COUNT;i++)if(STORY[i].node==node && STORY[i].when==when)return &STORY[i];
    return NULL;
}
